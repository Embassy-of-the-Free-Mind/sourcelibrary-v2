import { MongoClient } from 'mongodb';
import { put } from '@vercel/blob';

async function checkUrl(url) {
  try {
    const resp = await fetch(url, { method: 'HEAD', signal: AbortSignal.timeout(10000), redirect: 'follow' });
    return resp.status < 400;
  } catch {
    return false;
  }
}

function extractIaIdentifier(url) {
  // https://archive.org/download/IDENTIFIER/page/...
  const m = url.match(/archive\.org\/download\/([^/]+)/);
  return m ? m[1] : null;
}

async function tryOpenLibraryCover(iaId) {
  // Open Library has covers indexed by IA identifier
  // -L = large, -M = medium
  const url = `https://covers.openlibrary.org/b/ia/${iaId}-L.jpg`;
  try {
    const resp = await fetch(url, { signal: AbortSignal.timeout(10000), redirect: 'follow' });
    if (!resp.ok) return null;
    // OL returns a 1x1 pixel for missing covers — check content-length
    const contentLength = resp.headers.get('content-length');
    if (contentLength && parseInt(contentLength) < 1000) return null;
    const buffer = Buffer.from(await resp.arrayBuffer());
    if (buffer.length < 1000) return null; // tiny placeholder
    return buffer;
  } catch {
    return null;
  }
}

async function tryIaCoverImage(iaId) {
  // IA stores cover images at a different path than page images
  // __ia_thumb.jpg is generated by IA and may still be accessible
  const urls = [
    `https://archive.org/services/img/${iaId}`,
    `https://ia800107.us.archive.org/services/img/${iaId}`,
  ];
  for (const url of urls) {
    try {
      const resp = await fetch(url, { signal: AbortSignal.timeout(10000), redirect: 'follow' });
      if (!resp.ok) continue;
      const buffer = Buffer.from(await resp.arrayBuffer());
      if (buffer.length < 1000) continue;
      return buffer;
    } catch {
      continue;
    }
  }
  return null;
}

async function main() {
  const client = new MongoClient(process.env.MONGODB_URI);
  await client.connect();
  const db = client.db('bookstore');

  // Find broken IA/Harvard thumbnail books with no local page images
  const books = await db.collection('books').find({
    $or: [
      { thumbnail: { $regex: /archive\.org\/download/ } },
      { thumbnail: { $regex: /ids\.lib\.harvard\.edu/ } },
    ],
    pages_count: { $gt: 0 },
  }).project({ title: 1, thumbnail: 1, id: 1, _id: 0 }).toArray();

  // Check which are broken
  const brokenBooks = [];
  const BATCH = 30;
  for (let i = 0; i < books.length; i += BATCH) {
    const batch = books.slice(i, i + BATCH);
    const results = await Promise.all(batch.map(b => checkUrl(b.thumbnail)));
    for (let j = 0; j < batch.length; j++) {
      if (!results[j]) brokenBooks.push(batch[j]);
    }
  }

  // Filter to only those without local page images
  const noLocal = [];
  for (const book of brokenBooks) {
    const hasLocal = await db.collection('pages').findOne(
      { book_id: book.id, $or: [
        { thumbnail_blob: { $exists: true, $ne: null, $ne: '' } },
        { cropped_photo: { $exists: true, $ne: null, $ne: '' } },
        { archived_photo: { $exists: true, $ne: null, $ne: '' } },
      ]},
      { projection: { _id: 1 } }
    );
    if (!hasLocal) noLocal.push(book);
  }

  console.log(`${noLocal.length} books with broken thumbnails and no local images\n`);

  let fixedOL = 0, fixedIA = 0, failed = 0;

  for (const book of noLocal) {
    const iaId = extractIaIdentifier(book.thumbnail);

    // Try IA cover service first (different endpoint, often accessible even for restricted books)
    let imageBuffer = null;
    let source = '';

    if (iaId) {
      imageBuffer = await tryIaCoverImage(iaId);
      if (imageBuffer) source = 'ia_cover_service';
    }

    // Fallback: Open Library
    if (!imageBuffer && iaId) {
      imageBuffer = await tryOpenLibraryCover(iaId);
      if (imageBuffer) source = 'open_library';
    }

    if (!imageBuffer) {
      console.log(`  FAILED: ${book.title?.substring(0, 70)}`);
      failed++;
      continue;
    }

    // Upload to Vercel Blob
    try {
      const blob = await put(`thumbnails/${book.id}/cover.jpg`, imageBuffer, {
        access: 'public',
        contentType: 'image/jpeg',
        addRandomSuffix: false,
      });
      await db.collection('books').updateOne({ id: book.id }, { $set: { thumbnail: blob.url } });
      console.log(`  FIXED (${source}): ${book.title?.substring(0, 60)}`);
      if (source === 'open_library') fixedOL++;
      else fixedIA++;
    } catch (err) {
      console.log(`  UPLOAD FAILED: ${book.title?.substring(0, 60)} | ${err.message}`);
      failed++;
    }
  }

  console.log(`\n=== Results ===`);
  console.log(`Fixed via IA cover service: ${fixedIA}`);
  console.log(`Fixed via Open Library: ${fixedOL}`);
  console.log(`Still broken: ${failed}`);

  await client.close();
}

main();
