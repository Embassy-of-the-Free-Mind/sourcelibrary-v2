#!/usr/bin/env node
/**
 * Generates scripts/eval/EXPERIMENTS.md from scripts/eval/experiments/*.md.
 *
 * PRIOR ART: scripts/eval/build-index.mjs — generates INDEX.md from script
 * docstrings; same shape (sources → one committed file), different sources, so
 * it is the model here and not reusable as-is.
 *
 * WHY (#5436). EXPERIMENTS.md was an append-only ledger that every eval PR
 * appended one entry to. Two PRs appending to the same tail are a textual
 * conflict by construction: 6 of the 11 PRs labelled `needs-rebase` on
 * 2026-10-01 conflicted on this one file, and auto-merge never merges a
 * conflicting PR. GitHub's mergeability check does not honour `.gitattributes
 * merge=union`, so the attribute alone fixes nothing server-side. The fix is
 * structural: each entry is its own file under `experiments/`, so two PRs add
 * two files and never touch the same hunk. EXPERIMENTS.md stays as the
 * readable, greppable whole — but GENERATED, and regenerated on `main` by
 * `.github/workflows/eval-ledgers-regenerate.yml` after each merge. A PR never
 * edits it (CI: scripts/audit/append-only-ledgers.mjs --pr).
 *
 * Layout of scripts/eval/experiments/:
 *   README.md                 the header and the rules (hand-edited; copied verbatim)
 *   _series-<slug>.md         standing series (one table, a row per run) — rendered first
 *   YYYY-MM-DD-<slug>.md      one entry per question, heading `## YYYY-MM-DD · <question>`
 *                             — rendered newest first
 *   _note-<slug>.md           notes about the log itself — rendered last
 *
 *   node scripts/eval/build-experiments.mjs           # write EXPERIMENTS.md (on main, or with --force)
 *   node scripts/eval/build-experiments.mjs --check   # exit 1 if EXPERIMENTS.md is stale or a file is malformed
 *   node scripts/eval/build-experiments.mjs --print   # the generated text on stdout, write nothing
 *
 * The write refuses off `main` without --force: regenerating in a PR is the
 * habit that made the file a collider. View with --print; main regenerates it.
 *
 * A write first ADOPTS any dated entry that is in the committed EXPERIMENTS.md
 * but in no source file (a PR that still appended to the old file) into its own
 * file, so regeneration never drops an entry. See adoptOrphans().
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(DIR, 'experiments');
const OUT = path.join(DIR, 'EXPERIMENTS.md');
const argv = process.argv.slice(2);
const has = (f) => argv.includes(f);

const DATED = /^(\d{4}-\d{2}-\d{2})-[a-z0-9][a-z0-9-]*\.md$/;
const BANNER = [
  '<!-- GENERATED by scripts/eval/build-experiments.mjs from scripts/eval/experiments/*.md',
  '     on main, after each merge (eval-ledgers-regenerate.yml). Do not edit this file:',
  '     add ONE file under scripts/eval/experiments/ (see its README.md) and never touch',
  '     this one in a PR — two PRs appending here is the conflict #5436 removed. -->',
].join('\n');

/** Returns { text, problems[] }. */
export function buildExperiments(srcDir = SRC) {
  const problems = [];
  const names = fs.readdirSync(srcDir).filter((n) => n.endsWith('.md')).sort();
  const read = (n) => fs.readFileSync(path.join(srcDir, n), 'utf8').replace(/\s+$/, '') + '\n';

  if (!names.includes('README.md')) problems.push('experiments/README.md (the header) is missing');
  const header = names.includes('README.md') ? read('README.md') : '# Experiment log\n';
  const headerLines = header.split('\n');
  const withBanner = [headerLines[0], '', BANNER, ...headerLines.slice(1)].join('\n');

  const series = names.filter((n) => n.startsWith('_series-'));
  const notes = names.filter((n) => n.startsWith('_note-'));
  const dated = names.filter((n) => DATED.test(n)).sort().reverse(); // newest first
  for (const n of names) {
    if (n === 'README.md' || series.includes(n) || notes.includes(n) || dated.includes(n)) continue;
    problems.push(`${n}: not a dated entry (YYYY-MM-DD-slug.md), a _series-*.md or a _note-*.md`);
  }

  const sections = [];
  for (const n of [...series, ...dated, ...notes]) {
    const text = stripPriorArt(read(n));
    const first = text.split('\n')[0];
    if (!/^## /.test(first)) problems.push(`${n}: must start with a '## ' heading, starts with: ${first.slice(0, 60)}`);
    const m = n.match(DATED);
    if (m && !first.startsWith(`## ${m[1]}`)) problems.push(`${n}: heading date must match the filename (${m[1]}), got: ${first.slice(0, 40)}`);
    if (/^(<{7}|\|{7}|>{7})( |$)/m.test(text)) problems.push(`${n}: contains a merge-conflict marker`);
    sections.push(text.trimEnd());
  }

  const text = `${withBanner.trimEnd()}\n\n---\n\n${sections.join('\n\n')}\n`;
  return { text, problems, counts: { series: series.length, dated: dated.length, notes: notes.length } };
}

/**
 * The prior-art hook (.claude/hooks/prior-art-guard.mjs) makes every new file
 * here carry a `PRIOR ART: …` line, and sessions put it on line 1 — bare or in
 * an HTML comment — above the `## YYYY-MM-DD` heading. It is provenance for the
 * hook, not part of the entry: drop leading PRIOR ART lines (and the blank lines
 * after them) before the heading check, and keep them out of EXPERIMENTS.md.
 */
export function stripPriorArt(text) {
  const lines = text.split('\n');
  let i = 0;
  while (i < lines.length && (/^\s*(<!--\s*)?PRIOR ART:.*$/.test(lines[i]) || (i > 0 && lines[i].trim() === ''))) i++;
  return i ? lines.slice(i).join('\n') : text;
}

/**
 * Transition safety: a PR opened before #5436 (or one that ignored the gate) can
 * still land an entry in the committed EXPERIMENTS.md. Regenerating would drop
 * it silently. So before a write, every dated `## YYYY-MM-DD …` section in the
 * committed file whose heading is in none of the source files is ADOPTED: written
 * to experiments/YYYY-MM-DD-<slug>.md. Returns the files created.
 */
export function adoptOrphans(outPath = OUT, srcDir = SRC) {
  if (!fs.existsSync(outPath)) return [];
  const text = fs.readFileSync(outPath, 'utf8');
  const known = new Set();
  for (const n of fs.readdirSync(srcDir)) {
    if (!n.endsWith('.md') || n === 'README.md') continue;
    known.add(stripPriorArt(fs.readFileSync(path.join(srcDir, n), 'utf8')).split('\n')[0].trim());
  }
  const lines = text.split('\n');
  const starts = lines.flatMap((l, i) => (/^## /.test(l) ? [i] : []));
  const slug = (s) => s.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ').trim().split(' ').filter(Boolean);
  const created = [];
  for (let k = 0; k < starts.length; k++) {
    const a = starts[k], b = k + 1 < starts.length ? starts[k + 1] : lines.length;
    const heading = lines[a].trim();
    const m = heading.match(/^## (20\d\d-\d\d-\d\d)\b\s*(.*)$/);
    if (!m || known.has(heading)) continue;
    const body = lines.slice(a, b);
    while (body.length && (body[body.length - 1].trim() === '' || body[body.length - 1].trim() === '---')) body.pop();
    const issue = (m[2].match(/#(\d{3,5})/) || [])[1];
    let words = slug(m[2].replace(/\(#[^)]*\)/g, '').replace(/\(logged [^)]*\)/g, '')).slice(0, 9).join('-') || 'entry';
    if (issue) words += `-${issue}`;
    let name = `${m[1]}-${words}`, n = 2;
    while (fs.existsSync(path.join(srcDir, `${name}.md`))) name = `${m[1]}-${words}-${n++}`;
    fs.writeFileSync(path.join(srcDir, `${name}.md`), body.join('\n') + '\n');
    known.add(heading);
    created.push(`${name}.md`);
  }
  return created;
}

function currentBranch() {
  try { return execFileSync('git', ['branch', '--show-current'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); }
  catch { return ''; }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const writing = !has('--print') && !has('--check');
  if (writing) {
    const adopted = adoptOrphans();
    for (const n of adopted) console.log(`adopted an entry still written to EXPERIMENTS.md → experiments/${n}`);
  }
  const { text, problems, counts } = buildExperiments();
  for (const p of problems) console.error(`build-experiments: ${p}`);
  if (has('--print')) { process.stdout.write(text); process.exit(problems.length ? 1 : 0); }
  if (has('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('EXPERIMENTS.md is stale — main regenerates it (eval-ledgers-regenerate.yml); locally: --print, or --force to write'); process.exit(1); }
    if (problems.length) process.exit(1);
    console.log(`EXPERIMENTS.md is current (${counts.dated} entries, ${counts.series} series, ${counts.notes} notes)`);
    process.exit(0);
  }
  if (problems.length) process.exit(1);
  const branch = currentBranch();
  if (branch && branch !== 'main' && !has('--force')) {
    console.error(`refusing to write EXPERIMENTS.md on branch '${branch}': it is generated on main after merge.\n` +
      'Add your entry as a file under scripts/eval/experiments/ and leave EXPERIMENTS.md alone (--print to view, --force to override).');
    process.exit(2);
  }
  fs.writeFileSync(OUT, text);
  console.log(`wrote EXPERIMENTS.md (${counts.dated} entries, ${counts.series} series, ${counts.notes} notes)`);
}
