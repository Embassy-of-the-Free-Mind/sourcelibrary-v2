#!/usr/bin/env node
/**
 * PRIOR ART: scripts/eval/recommend-experiments.mjs ranks experiments still
 * WORTH RUNNING; it does not describe what already exists. No index of the eval
 * directory was found (`ls scripts/eval/*.md` → two preregistrations and a few
 * runbooks, no map). This fills that gap and nothing else.
 *
 * Generates scripts/eval/INDEX.md from the first sentence of each script's
 * docstring, plus the exported surface of scripts/eval/lib.
 *
 * GENERATED, never hand-edited — a hand-maintained index of 134 files drifts
 * within a month and then actively misleads, which is worse than no index. If
 * a script is described wrongly here, fix its DOCSTRING and re-run.
 *
 *   node scripts/eval/build-index.mjs [--check]
 *
 * --check exits non-zero if INDEX.md is stale, for CI or a pre-commit hook.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(DIR, 'INDEX.md');
const SKIP_DIRS = new Set(['results', 'observations', 'dataset', 'transcripts', 'fixtures',
  'ground-truth', 'prompts', 'reference-works', 'suda-sol', 'librarian-search', '_archived']);

/** First real sentence of the leading block comment. */
function summarise(file) {
  let text = '';
  try { text = fs.readFileSync(file, 'utf8').slice(0, 3000); } catch { return ''; }
  const block = text.match(/\/\*\*([\s\S]*?)\*\//);
  let body = block
    ? block[1].split('\n').map((l) => l.replace(/^\s*\*ā?\s?/, '').replace(/^\s*\*\s?/, '').trim()).join(' ')
    : (text.match(/^(?:#[^\n]*\n)?((?:\/\/[^\n]*\n)+)/m)?.[1] || '').replace(/\/\//g, ' ');
  body = body.replace(/PRIOR[ -]ART:[^.]*\./gi, '').replace(/\s+/g, ' ').trim();
  const stop = body.search(/\.\s|$/);
  let s = body.slice(0, stop > 0 ? stop + 1 : 160).trim();
  if (s.length > 200) s = s.slice(0, 197) + '…';
  return s;
}

function walk(dir, out, depth = 0) {
  if (depth > 2) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || e.name.startsWith('_tmp')) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) walk(full, out, depth + 1); }
    else if (/\.(mjs|ts)$/.test(e.name)) out.push(full);
  }
}

const files = [];
walk(DIR, files);
files.sort();

const libExports = [];
const libDir = path.join(DIR, 'lib');
if (fs.existsSync(libDir)) {
  for (const f of fs.readdirSync(libDir).filter((f) => /\.mjs$/.test(f))) {
    const src = fs.readFileSync(path.join(libDir, f), 'utf8');
    const names = [...src.matchAll(/export (?:async )?(?:function|const) (\w+)/g)].map((m) => m[1]);
    if (names.length) libExports.push({ f, names });
  }
}

const rows = files
  .filter((f) => !f.includes(`${path.sep}lib${path.sep}`))
  .map((f) => ({ rel: path.relative(DIR, f), sum: summarise(f) }));

const md = `# scripts/eval — index

<!-- GENERATED by scripts/eval/build-index.mjs. Do not hand-edit: fix the
     script's docstring and re-run \`node scripts/eval/build-index.mjs\`. -->

${rows.length} scripts. Before writing a new one, look here and in
\`PREREGISTRATION-*.md\`; the prior-art guard will ask you what you checked.

## Reusable library — \`scripts/eval/lib/\`

**Check this first.** These are the pieces that have already been factored out;
re-implementing one is the most common way work gets duplicated here.

| module | exports |
|---|---|
${libExports.map((l) => `| \`lib/${l.f}\` | ${l.names.map((n) => `\`${n}\``).join(', ')} |`).join('\n')}

## Preregistrations

Experiments with hypotheses and decision rules fixed **before** the paid run.
Read these for the house conventions before designing a new study.

${fs.readdirSync(DIR).filter((f) => f.startsWith('PREREGISTRATION')).map((f) => `- \`${f}\``).join('\n')}

## Scripts

| script | what it does |
|---|---|
${rows.map((r) => `| \`${r.rel}\` | ${r.sum.replace(/\|/g, '\\|') || '—'} |`).join('\n')}
`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== md) { console.error('INDEX.md is stale — run: node scripts/eval/build-index.mjs'); process.exit(1); }
  console.log('INDEX.md is current');
} else {
  fs.writeFileSync(OUT, md);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} — ${rows.length} scripts, ${libExports.length} lib modules`);
}
