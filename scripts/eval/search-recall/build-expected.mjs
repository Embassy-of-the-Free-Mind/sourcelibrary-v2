#!/usr/bin/env node
/**
 * Build the expected-books file for the site-search recall eval (#5905).
 *
 * PRIOR ART: scripts/eval/librarian-search/_seed-golden-set.mjs — seeds
 * hand-validated (book, page-range) tuples for the Librarian's tools; this one
 * derives expected BOOKS from Atlas page counts, with no hand labels.
 *
 * For each query in queries.json, count the pages that print any of its
 * `expect_terms` as an exact phrase (Atlas `pages_search`, translation + OCR),
 * per book, with a facet — no page documents are read. The expected set is the
 * 20 live works with the most such pages.
 *
 * READ-ONLY. Run once and commit expected.json: the eval is only "fixed" if
 * the expected set does not move between the before and the after run.
 *
 *   node --env-file=.env.production.local scripts/eval/search-recall/build-expected.mjs
 */
import { MongoClient } from 'mongodb';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const TOP = 20;
const MIN_PAGES = 2;

const { queries } = JSON.parse(readFileSync(path.join(DIR, 'queries.json'), 'utf8'));
const client = new MongoClient(process.env.MONGODB_URI);
await client.connect();
const db = client.db(process.env.MONGODB_DB || 'bookstore');

/** Same grain the route collapses to (src/lib/search/work-grouping.ts), minus aliases. */
function groupKey(b) {
  if (typeof b.duplicate_of === 'string' && b.duplicate_of.trim()) return `copy:${b.duplicate_of.trim()}`;
  if (typeof b.work_id === 'string' && b.work_id.trim()) return `work:${b.work_id.trim()}`;
  return `book:${b.id}`;
}

const out = [];
for (const q of queries) {
  const should = q.expect_terms.flatMap(t => [
    { phrase: { query: t, path: 'translation.data' } },
    { phrase: { query: t, path: 'ocr.data' } },
  ]);
  const [meta] = await db.collection('pages').aggregate([{
    $searchMeta: {
      index: 'pages_search',
      facet: {
        operator: { compound: { should, minimumShouldMatch: 1, filter: [{ range: { path: 'page_number', gt: 0 } }] } },
        facets: { book: { type: 'string', path: 'book_id', numBuckets: 1000 } },
      },
    },
  }]).toArray();
  const buckets = meta.facet.book.buckets;
  const books = await db.collection('books')
    .find(
      { id: { $in: buckets.map(b => b._id) }, visible: true, hidden: { $ne: true }, pages_count: { $gt: 0 }, content_type: { $ne: 'artwork' } },
      { projection: { id: 1, title: 1, display_title: 1, author: 1, work_id: 1, duplicate_of: 1 } },
    ).toArray();
  const byId = new Map(books.map(b => [b.id, b]));
  const groups = new Map();
  for (const { _id, count } of buckets) {
    const b = byId.get(_id);
    if (!b) continue;
    const key = groupKey(b);
    const g = groups.get(key) || { key, pages: 0, book_ids: [], title: '', author: '' };
    // A work's evidence is its best edition's, not the sum over editions —
    // otherwise a much-reprinted work outranks a monograph on the subject.
    if (count > g.pages) {
      g.pages = count;
      g.title = String(b.display_title || b.title || '').replace(/\s+/g, ' ').trim().slice(0, 90);
      g.author = String(b.author || '').slice(0, 60);
    }
    g.book_ids.push(_id);
    groups.set(key, g);
  }
  const ranked = [...groups.values()].sort((a, b) => b.pages - a.pages);
  const strong = ranked.filter(g => g.pages >= MIN_PAGES);
  const expected = (strong.length >= 5 ? strong : ranked).slice(0, TOP);
  out.push({
    id: q.id,
    matching_pages: meta.count.lowerBound,
    // The facet returns at most 1,000 books, so this is a floor for common terms.
    matching_live_works: ranked.length,
    expected,
  });
  console.log(`${q.id.padEnd(32)} pages ${String(meta.count.lowerBound).padStart(6)}  live works ${String(ranked.length).padStart(4)}  expected ${expected.length} (pages ${expected[0]?.pages}…${expected.at(-1)?.pages})`);
}
writeFileSync(path.join(DIR, 'expected.json'), JSON.stringify({
  _prior_art: 'PRIOR ART: scripts/eval/librarian-search/golden-set.json — hand labels at page grain for the Librarian; this file is generated by build-expected.mjs from Atlas page counts.',
  built_at: new Date().toISOString(),
  rule: `top ${TOP} live works by pages printing any expect_term as a phrase (min ${MIN_PAGES} pages when at least 5 works reach it)`,
  queries: out,
}, null, 1) + '\n');
await client.close();
