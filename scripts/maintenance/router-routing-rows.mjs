#!/usr/bin/env node
// PRIOR ART: scripts/eval/build-routing-table.mjs — generates a doc SECTION from the routing constants and fails a test
// when it drifts (tests/unit/routing-table-fresh.test.ts); the same shape is used here, but its input is the live
// routers and DECISIONS.md, never the router table. scripts/audit/router-table-drift.mjs — reports whether each decided
// cell has shipped and whether a routing-table row names it, and writes nothing. scripts/eval/estimator/routing/
// derive_routes.py — proposes `route` fields for the hand rows from the routing estimator, not from current.json.
//
// router-routing-rows (#7913): the routing tables' CELL-BACKED rows, generated from the router table's current.json.
//
//   node scripts/maintenance/router-routing-rows.mjs            # --check: exit 1 when a table is not what this writes
//   node scripts/maintenance/router-routing-rows.mjs --write    # rewrite the `router_cells` block of both tables
//
// Every decided cell of current.json (keep / switch, not UNTESTED; scripts/lib/router-binding.mjs loadCurrentTable)
// becomes one row of the `router_cells` block of scripts/lib/ocr-routing-table.json (OCR cells) or
// translation-routing-table.json (translation cells: a base id ending in -tr or containing -tr-). The block is the LAST
// key of the table and the only part this writes: the hand rows (`rows`: provider, Loeb, BPH, policy matches) and every
// other key stay byte for byte. A decision ships by moving the pointer; the CI test (tests/unit/router-routing-rows-7913
// .test.ts) fails until the block is regenerated, so the routing table and the decision cannot disagree in main.
// Nothing reads `router_cells` to route a book: lanes bind through routeCheck (router-binding.mjs), the Batch routers
// read the hand rows. Read-only on everything but the two JSON files.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCurrentTable, ROUTER_DIR } from '../lib/router-binding.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const TABLES = { ocr: 'scripts/lib/ocr-routing-table.json', translation: 'scripts/lib/translation-routing-table.json' };
export const KEY = 'router_cells';

const decided = (row) => /^(keep|switch)\b/.test(row.decision || '') && !/UNTESTED/.test(row.decision);
/** The router's own split (build.py judge_stratum): a translation cell's base id ends in -tr or has -tr- in it. */
export const isTranslationCell = (row) => /-tr(-|$)/.test(row.base || String(row.id).split('/')[0]);

/** The generated rows, {ocr: [...], translation: [...]}, from loadCurrentTable's shape. Sorted by cell. */
export function cellRows(table) {
  const out = { ocr: [], translation: [] };
  const ids = [...table.rows.keys()].sort();
  for (const id of ids) {
    const row = table.rows.get(id);
    if (!decided(row)) continue;
    const r = (row.routes || []).find((x) => x.id === row.route);
    const moved = table.pointer?.cells?.[id];
    const waivers = (table.waivers || []).filter((w) => w.cell === id).map((w) => ({ ...(w.lane && { lane: w.lane }), set: w.set, until: w.until }));
    out[isTranslationCell(row) ? 'translation' : 'ocr'].push({
      cell: id,
      decision: String(row.decision).split(' (')[0],
      route: row.route,
      k_of_n: r && r.n ? `${r.k}/${r.n}` : null,
      table: moved?.table || table.name,
      set: moved?.set || table.pointer?.set || null,
      ...(waivers.length && { waivers }),
    });
  }
  return out;
}

const DOC = 'GENERATED by scripts/maintenance/router-routing-rows.mjs from scripts/eval/estimator/router-table/current.json (#7913): one row per decided cell (keep / switch) of the live router table, its route, the route\'s judged k/n, the build the decision comes from and any waiver. Do not edit: move the pointer in current.json and run the script with --write; tests/unit/router-routing-rows-7913.test.ts fails while this block and current.json disagree. Lanes bind to these decisions through routeCheck (scripts/lib/router-binding.mjs); the routers read `rows` and `default`, not this block.';

/** The table text with its `router_cells` block (always the last key) replaced by `rows`. Every other byte stays. */
export function withCellRows(text, rows) {
  const parsed = JSON.parse(text);
  let body = text.replace(/\s*$/, '');
  if (!body.endsWith('}')) throw new Error('routing table: expected a JSON object');
  if (KEY in parsed) {
    const keys = Object.keys(parsed);
    if (keys[keys.length - 1] !== KEY) throw new Error(`routing table: "${KEY}" must be the last key`);
    const at = body.lastIndexOf(`,\n  "_${KEY}": `);
    if (at < 0) throw new Error(`routing table: "_${KEY}" must stand just before "${KEY}"`);
    body = body.slice(0, at) + '\n}';
  }
  const block = JSON.stringify({ [`_${KEY}`]: DOC, [KEY]: rows }, null, 2).slice(1, -2);
  return `${body.slice(0, -1).replace(/\s*$/, '')},${block}\n}\n`;
}

/** {file: {current, wanted}} for both tables. */
export function plan({ root = ROOT, dir = ROUTER_DIR } = {}) {
  const rows = cellRows(loadCurrentTable(dir));
  return Object.fromEntries(Object.entries(TABLES).map(([k, f]) => {
    const current = fs.readFileSync(path.join(root, f), 'utf8');
    return [f, { current, wanted: withCellRows(current, rows[k]), rows: rows[k] }];
  }));
}

function main() {
  const p = plan();
  const stale = Object.entries(p).filter(([, x]) => x.current !== x.wanted);
  if (process.argv.includes('--write')) {
    for (const [f, x] of stale) fs.writeFileSync(path.join(ROOT, f), x.wanted);
    console.log(stale.length ? `wrote ${stale.map(([f]) => f).join(', ')}` : 'both tables already current');
    for (const [f, x] of Object.entries(p)) console.log(`${f}: ${x.rows.length} router cells`);
    return;
  }
  for (const [f] of stale) console.error(`${f}: router_cells is not what current.json gives; run node scripts/maintenance/router-routing-rows.mjs --write`);
  process.exit(stale.length ? 1 : 0);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
