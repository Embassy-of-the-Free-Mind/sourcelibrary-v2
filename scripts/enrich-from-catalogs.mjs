// ── Supabase REST client ────────────────────────────────────────────

async function supabaseQuery(table, params = {}, { wantCount = false } = {}) {
  const url = new URL(`${SUPABASE_URL}/rest/v1/${table}`);

  for (const [key, value] of Object.entries(params)) {
    url.searchParams.set(key, value);
  }

  const headers = {
    'apikey': SUPABASE_ANON_KEY,
    'Authorization': `Bearer ${SUPABASE_ANON_KEY}`,
    'Accept': 'application/json',
  };

  // IMPORTANT: count=exact causes full table scans that time out on large tables.
  // Only request it when explicitly needed (small result sets).
  if (wantCount) {
    headers['Prefer'] = 'count=exact';
  }

  const resp = await fetch(url.toString(), {
    headers,
    signal: AbortSignal.timeout(15000),
  });

  if (!resp.ok) {
    const text = await resp.text();
    throw new Error(`Supabase ${resp.status}: ${text.substring(0, 200)}`);
  }

  const totalCount = resp.headers.get('content-range')?.split('/')[1];
  const data = await resp.json();
  return { data, totalCount: totalCount ? parseInt(totalCount) : null };
}

// Helper: run Supabase RPC (for full-text search)
async function supabaseRpc(fnName, params = {}) {
  const url = `${SUPABASE_URL}/rest/v1/rpc/${fnName}`;

  const resp = await fetch(url, {
    method: 'POST',
    headers: {
      'apikey': SUPABASE_ANON_KEY,
      'Authorization': `Bearer ${SUPABASE_ANON_KEY}`,
      'Accept': 'application/json',
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(params),
    signal: AbortSignal.timeout(15000),
  });

  if (!resp.ok) {
    const text = await resp.text();
    throw new Error(`Supabase RPC ${resp.status}: ${text.substring(0, 200)}`);
  }

  return await resp.json();
}

// ── Text normalization for matching ─────────────────────────────────

function normalizeForMatch(text) {
  return (text || '')
    .toLowerCase()
    .replace(/[^\w\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function extractKeywords(title) {
  const stopWords = new Set([
    'the', 'and', 'for', 'with', 'from', 'that', 'this', 'into', 'upon', 'which',
    'book', 'part', 'vol', 'volume', 'edition', 'page', 'being', 'containing',
    'also', 'very', 'most', 'wherein', 'thereof', 'hath', 'doth', 'unto',
    'liber', 'libri', 'opus', 'item', 'sive', 'sicut', 'atque', 'quae', 'quod',
    'cum', 'per', 'pro', 'sed', 'non', 'enim', 'etiam', 'eius', 'alia', 'omnia',
    'des', 'der', 'die', 'und', 'von', 'das', 'ein', 'eine', 'les', 'des', 'del',
  ]);

  return normalizeForMatch(title)
    .split(/\s+/)
    .filter(w => w.length > 3 && !stopWords.has(w));
}

// ── BPH matching (via ia_identifier) ────────────────────────────────

async function matchBPH(db, books, dryRun) {
  console.log('\n=== PHASE 1: BPH Matching (ia_identifier) ===\n');

  const booksWithIA = books.filter(b => b.ia_identifier);
  console.log(`Books with IA identifier: ${booksWithIA.length}`);

  if (booksWithIA.length === 0) {
    console.log('No books with IA identifiers to match.');
    return { matched: 0, total: 0 };
  }

  // Fetch ALL BPH records that have ia_identifier set
  let allBphWithIA = [];
  let offset = 0;
  const pageSize = 1000;

  console.log('Fetching BPH records with IA identifiers...');
  while (true) {
    const { data } = await supabaseQuery('bph_works', {
      'select': 'id,ubn,title,author,year,year_raw,place,printer,publisher,keywords,language,ia_identifier,ia_url,ia_match_confidence,remarks,bibliography',
      'ia_identifier': 'not.is.null',
      'offset': offset,
      'limit': pageSize,
    });
    allBphWithIA.push(...data);
    if (data.length < pageSize) break;
    offset += pageSize;
  }

  console.log(`BPH records with IA links: ${allBphWithIA.length}`);

  // Build lookup by ia_identifier
  const bphByIA = new Map();
  for (const bph of allBphWithIA) {
    if (bph.ia_identifier) {
      bphByIA.set(bph.ia_identifier, bph);
    }
  }

  let matched = 0;
  let updated = 0;

  for (const book of booksWithIA) {
    const bph = bphByIA.get(book.ia_identifier);
    if (!bph) continue;

    matched++;
    const shortTitle = (book.display_title || book.title || '').substring(0, 55);

    const enrichments = {};
    const changes = [];

    // Year from BPH (cataloger-verified) — ORIGINAL catalog data
    if (!book.year && bph.year) {
      enrichments.year = bph.year;
      enrichments.published = String(bph.year);
      changes.push(`year: ${bph.year}`);
    }

    if (bph.place && !book.publication_place) {
      enrichments.publication_place = bph.place;
      changes.push(`place: ${bph.place}`);
    }

    if (bph.printer && !book.printer) {
      enrichments.printer = bph.printer;
      changes.push(`printer: ${bph.printer}`);
    }

    // BPH keywords → SL categories mapping
    if (bph.keywords) {
      const bphToSLCategory = {
        'alchemy': 'alchemy',
        'hermetica': 'hermeticism',
        'hermeticism': 'hermeticism',
        'kabbalah': 'jewish-kabbalah',
        'cabala': 'christian-cabala',
        'rosicrucianism': 'rosicrucianism',
        'freemasonry': 'freemasonry',
        'mysticism': 'mysticism',
        'esotericism': 'mysticism',
        'theosophy': 'theosophy',
        'astrology': 'astrology',
        'magic': 'natural-magic',
        'neoplatonism': 'neoplatonism',
        'gnosticism': 'gnosticism',
        'paracelsian': 'paracelsian',
        'medicine': 'medicine',
        'theology': 'theology',
        'philosophy': 'philosophy',
      };

      const bphKeywords = bph.keywords.toLowerCase().split(/[,;/]+/).map(k => k.trim());
      const mappedCategories = bphKeywords
        .map(k => bphToSLCategory[k])
        .filter(Boolean);

      if (mappedCategories.length > 0) {
        const existing = book.categories || [];
        const merged = [...new Set([...existing, ...mappedCategories])];
        if (merged.length > existing.length) {
          enrichments.categories = merged;
          changes.push(`categories: +${mappedCategories.join(',')}`);
        }
      }
    }

    const changeStr = changes.length > 0 ? changes.join(' | ') : 'no new fields';
    console.log(`  BPH ${bph.ia_match_confidence || '?'}: ${shortTitle}`);
    console.log(`    → BPH: ${(bph.title || '').substring(0, 60)} (${bph.year || '?'})`);
    console.log(`    → ${changeStr}`);

    if (!dryRun) {
      const now = new Date();
      const catalogRef = {
        source: 'bph',
        bph_id: bph.id,
        bph_ubn: bph.ubn,
        match_method: 'ia_identifier',
        match_confidence: bph.ia_match_confidence || 'high',
        matched_at: now,
        // Original BPH catalog fields
        bph_title: bph.title,
        bph_author: bph.author,
        bph_year: bph.year,
        bph_place: bph.place,
        bph_printer: bph.printer,
        bph_keywords: bph.keywords,
        data_provenance: 'bph_catalog_original',
      };

      const update = {
        $set: { ...enrichments, updated_at: now },
        $addToSet: { catalog_refs: catalogRef },
      };

      if (changes.length > 0) {
        const provenance = book.field_provenance || {};
        const bphSource = {
          source: 'bph_catalog',
          provenance_type: 'original_catalog', // NOT AI — this is cataloger data
          bph_id: bph.id,
          date: now,
          confidence: 'high',
          script: 'enrich-from-catalogs.mjs',
        };
        if (enrichments.year) provenance.year = { ...bphSource, previous_value: book.year || null };
        if (enrichments.categories) provenance.categories = { ...bphSource, previous_value: book.categories || [], note: 'merged with BPH keywords' };
        if (enrichments.publication_place) provenance.publication_place = bphSource;
        if (enrichments.printer) provenance.printer = bphSource;
        update.$set.field_provenance = provenance;
      }

      await db.collection('books').updateOne({ id: book.id }, update);
      updated++;
    }
  }

  console.log(`\nBPH: ${matched} matched, ${updated} updated out of ${booksWithIA.length} books with IA IDs`);
  return { matched, updated, total: booksWithIA.length };
}

// ── USTC matching (year + title keywords) ───────────────────────────
//
// Strategy: USTC's `year` column is indexed. Query by exact year first
// (massive reduction from 1.6M to ~20K), then filter by title keywords
// client-side. This avoids full-text ilike scans that time out.

async function matchUSTC(db, books, dryRun) {
  console.log('\n=== PHASE 2: USTC Matching (year + title) ===\n');

  const candidates = books.filter(b => {
    const year = b.year || parseInt(b.published) || 0;
    const inRange = year >= 1400 && year <= 1750;
    const hasRef = (b.catalog_refs || []).some(r => r.source === 'ustc');
    return inRange && !hasRef;
  });

  const noYearBooks = books.filter(b => {
    const year = b.year || parseInt(b.published) || 0;
    return !year && !(b.catalog_refs || []).some(r => r.source === 'ustc');
  });

  console.log(`USTC candidates (with year 1400-1750, no existing ref): ${candidates.length}`);
  if (noYearBooks.length > 0) {
    console.log(`  (${noYearBooks.length} books skipped — no year for USTC matching)`);
  }

  let highMatches = 0, medMatches = 0;
  let updated = 0, noMatch = 0, errors = 0;

  // Group candidates by year for batch fetching
  const byYear = new Map();
  for (const book of candidates) {
    const year = book.year || parseInt(book.published);
    if (!byYear.has(year)) byYear.set(year, []);
    byYear.get(year).push(book);
  }

  const years = [...byYear.keys()].sort((a, b) => a - b);
  console.log(`Unique years to query: ${years.length}`);

  // Process year by year — each query hits the idx_ustc_year index
  for (let yi = 0; yi < years.length; yi++) {
    const year = years[yi];
    const yearBooks = byYear.get(year);

    try {
      // Fetch USTC editions for this year
      let ustcForYear = [];
      let offset = 0;
      const pageSize = 1000;

      while (true) {
        const { data } = await supabaseQuery('ustc_editions', {
          'select': 'id,title,author_1,author_2,year,place,printer_1,format,language_1,language_2,classification_1,classification_2,country,region,imprint',
          'year': `eq.${year}`,
          'offset': offset,
          'limit': pageSize,
        });
        ustcForYear.push(...data);
        if (data.length < pageSize) break;
        offset += pageSize;
      }

      if (ustcForYear.length === 0) {
        noMatch += yearBooks.length;
        continue;
      }

      // Pre-process USTC titles for keyword matching (no API calls needed)
      const ustcProcessed = ustcForYear.map(u => ({
        ...u,
        _keywords: extractKeywords(u.title),
        _authorLower: normalizeForMatch(u.author_1),
      }));

      // Match each SL book against USTC records for this year
      for (const book of yearBooks) {
        const bookKeywords = extractKeywords(book.display_title || book.title || '');
        const bookAuthorLower = normalizeForMatch(book.author || '');
        const shortTitle = (book.display_title || book.title || '').substring(0, 55);

        if (bookKeywords.length < 2) {
          noMatch++;
          continue;
        }

        // PASS 1: Score against ORIGINAL titles only (fast, no API calls)
        // Track title and author scores separately so re-scoring works correctly
        const scored = ustcProcessed.map(ustc => {
          const origOverlap = bookKeywords.filter(bk =>
            ustc._keywords.some(uk => uk.includes(bk) || bk.includes(uk))
          );
          const titleScore = (origOverlap.length / Math.max(bookKeywords.length, 1)) * 50;

          let authorBonus = 0;
          if (bookAuthorLower && ustc._authorLower) {
            const authorWords = bookAuthorLower.split(/\s+/).filter(w => w.length > 2);
            const ustcAuthorWords = ustc._authorLower.split(/\s+/).filter(w => w.length > 2);
            const authorOverlap = authorWords.filter(w =>
              ustcAuthorWords.some(uw => uw.includes(w) || w.includes(uw))
            );
            if (authorOverlap.length > 0) authorBonus = 30;
          }

          const yearBonus = 20; // Already filtered by year
          const total = titleScore + authorBonus + yearBonus;

          return { ustc, titleScore, authorBonus, yearBonus, score: total, method: 'original_title' };
        }).filter(s => s.score >= 30); // Minimum for original-title pass

        // PASS 2: Fetch enrichments for top 30 candidates only
        const topCandidates = scored.sort((a, b) => b.score - a.score).slice(0, 30);

        if (topCandidates.length > 0) {
          const topIds = topCandidates.map(c => c.ustc.id);
          try {
            const { data: enrichData } = await supabaseQuery('ustc_enrichments', {
              'select': 'id,english_title,detected_language,work_type,subject_tags,religious_tradition,original_author,classical_source',
              'id': `in.(${topIds.join(',')})`,
              'limit': String(topIds.length),
            });
            for (const e of enrichData) {
              const candidate = topCandidates.find(c => c.ustc.id === e.id);
              if (candidate) {
                candidate.ustc._enrichment = e;
                // Re-score with english_title — keep author and year bonuses, replace title score
                if (e.english_title) {
                  const enKeywords = extractKeywords(e.english_title);
                  const enOverlap = bookKeywords.filter(bk =>
                    enKeywords.some(ek => ek.includes(bk) || bk.includes(ek))
                  );
                  const enTitleScore = (enOverlap.length / Math.max(bookKeywords.length, 1)) * 50;
                  if (enTitleScore > candidate.titleScore) {
                    candidate.titleScore = enTitleScore;
                    candidate.score = enTitleScore + candidate.authorBonus + candidate.yearBonus;
                    candidate.method = 'english_title';
                  }
                }
              }
            }
          } catch (enrichErr) {
            // Enrichment failing is OK — use original title scores
          }
        }

        // Find best match after re-scoring
        let bestMatch = null;
        let bestScore = 0;
        let bestMatchMethod = 'original_title';

        for (const candidate of topCandidates) {
          if (candidate.score > bestScore) {
            bestScore = candidate.score;
            bestMatch = candidate.ustc;
            bestMatchMethod = candidate.method;
          }
        }

        // Reject low confidence entirely (score < 70)
        if (!bestMatch || bestScore < 70) {
          noMatch++;
          continue;
        }

        const confidence = bestScore >= 85 ? 'high' : 'medium';
        const enrichment = bestMatch._enrichment || null;

        if (confidence === 'high') highMatches++;
        else medMatches++;

        const matchedEnTitle = enrichment?.english_title
          ? ` [en: ${enrichment.english_title.substring(0, 40)}]`
          : '';
        console.log(`  [y${year}] USTC ${confidence} (${bestScore.toFixed(0)}, ${bestMatchMethod}): ${shortTitle}`);
        console.log(`    → USTC #${bestMatch.id}: ${(bestMatch.title || '').substring(0, 55)}${matchedEnTitle}`);

        // Build enrichments — auto-apply for both high and medium
        const enrichments = {};
        const changes = [];

        {
          if (bestMatch.place && !book.publication_place) {
            enrichments.publication_place = bestMatch.place;
            changes.push(`place: ${bestMatch.place}`);
          }
          if (bestMatch.printer_1 && !book.printer) {
            enrichments.printer = bestMatch.printer_1;
            changes.push(`printer: ${bestMatch.printer_1}`);
          }
          if (bestMatch.format && !book.format) {
            enrichments.format = bestMatch.format;
            changes.push(`format: ${bestMatch.format}`);
          }
          if (bestMatch.language_1 && (!book.language || book.language === 'Unknown')) {
            enrichments.language = bestMatch.language_1;
            changes.push(`language: ${bestMatch.language_1}`);
          }

          // USTC classification → SL categories
          const classToCategory = {
            'Religious': 'theology', 'Law': 'law', 'Science and Technology': 'natural-philosophy',
            'Philosophy': 'philosophy', 'Medicine': 'medicine', 'Music': 'music',
            'Literature': 'literature', 'History': 'history', 'Education': 'education',
          };
          for (const cls of [bestMatch.classification_1, bestMatch.classification_2].filter(Boolean)) {
            const cat = classToCategory[cls];
            if (cat) {
              const existing = book.categories || enrichments.categories || [];
              if (!existing.includes(cat)) {
                enrichments.categories = [...new Set([...existing, cat])];
                changes.push(`category: +${cat}`);
              }
            }
          }

          // AI enrichments (english_title, work_type, subject_tags)
          if (enrichment) {
            if (enrichment.english_title && !book.english_title) {
              enrichments.english_title = enrichment.english_title;
              changes.push(`en_title: ${enrichment.english_title.substring(0, 40)}`);
            }
            if (enrichment.work_type) {
              enrichments.ustc_work_type = enrichment.work_type;
            }
            if (enrichment.subject_tags) {
              let tags = enrichment.subject_tags;
              if (typeof tags === 'string') {
                try { tags = JSON.parse(tags); } catch { tags = [tags]; }
              }
              if (Array.isArray(tags) && tags.length > 0) {
                const existing = book.categories || enrichments.categories || [];
                const merged = [...new Set([...existing, ...tags])];
                if (merged.length > existing.length) {
                  enrichments.categories = merged;
                  changes.push(`tags: +${tags.join(',')}`);
                }
              }
            }
          }

          if (changes.length > 0) {
            console.log(`    → AUTO: ${changes.join(' | ')}`);
          }
        }

        if (!dryRun) {
          const now = new Date();
          const catalogRef = {
            source: 'ustc',
            ustc_id: bestMatch.id,
            match_method: `year_${bestMatchMethod}`,
            match_confidence: confidence,
            match_score: bestScore,
            matched_at: now,
            // ORIGINAL USTC catalog data (always stored for reference)
            ustc_title: bestMatch.title,
            ustc_author: bestMatch.author_1,
            ustc_year: bestMatch.year,
            ustc_place: bestMatch.place,
            ustc_printer: bestMatch.printer_1,
            ustc_format: bestMatch.format,
            ustc_language: bestMatch.language_1,
            ustc_classification: bestMatch.classification_1,
            ustc_country: bestMatch.country,
            ustc_imprint: bestMatch.imprint,
            data_provenance: 'ustc_catalog_original',
          };

          if (enrichment) {
            catalogRef.ai_enrichment = {
              english_title: enrichment.english_title,
              work_type: enrichment.work_type,
              subject_tags: enrichment.subject_tags,
              religious_tradition: enrichment.religious_tradition,
              original_author: enrichment.original_author,
              classical_source: enrichment.classical_source,
              data_provenance: 'ustc_ai_enriched',
            };
          }

          const update = {
            $set: { updated_at: now },
            $addToSet: { catalog_refs: catalogRef },
          };

          // Apply field enrichments for medium+ confidence
          if (Object.keys(enrichments).length > 0) {
            Object.assign(update.$set, enrichments);

            const provenance = book.field_provenance || {};
            const ustcOriginal = {
              source: 'ustc_catalog',
              provenance_type: 'original_catalog',
              ustc_id: bestMatch.id,
              date: now,
              confidence,
              script: 'enrich-from-catalogs.mjs',
            };
            const ustcAI = {
              source: 'ustc_enrichments',
              provenance_type: 'ai_derived',
              ustc_id: bestMatch.id,
              date: now,
              confidence: 'medium',
              script: 'enrich-from-catalogs.mjs',
              note: 'AI-generated by Claude Haiku + Gemini Flash from USTC title',
            };

            if (enrichments.publication_place) provenance.publication_place = ustcOriginal;
            if (enrichments.printer) provenance.printer = ustcOriginal;
            if (enrichments.format) provenance.format = ustcOriginal;
            if (enrichments.language) provenance.language = { ...ustcOriginal, previous_value: book.language || null };
            if (enrichments.english_title) provenance.english_title = ustcAI;
            if (enrichments.categories) {
              provenance.categories = {
                ...ustcOriginal,
                previous_value: book.categories || [],
                note: 'merged from USTC classification + AI subject_tags',
              };
            }
            update.$set.field_provenance = provenance;
          }

          await db.collection('books').updateOne({ id: book.id }, update);
          updated++;
        }
      }
    } catch (err) {
      console.log(`  ERROR year ${year}: ${err.message}`);
      errors++;
    }

    // Progress
    if ((yi + 1) % 20 === 0) {
      console.log(`  ... processed ${yi + 1}/${years.length} years`);
    }

    // Small delay every 5 years
    if (yi % 5 === 4) {
      await new Promise(r => setTimeout(r, 100));
    }
  }

  const totalMatched = highMatches + medMatches;
  console.log(`\nUSTC results:`);
  console.log(`  high confidence (auto-applied): ${highMatches}`);
  console.log(`  medium confidence (auto-applied): ${medMatches}`);
  console.log(`  rejected (score < 70): ${noMatch}`);
  console.log(`  errors: ${errors}`);
  console.log(`  total: ${totalMatched} matched, ${updated} updated`);
  return { highMatches, medMatches, updated, noMatch, total: candidates.length };
}

// ── First-translation assessment ────────────────────────────────────
//
// Core question: is Source Library's translation of this book the FIRST
// time it has been made available in English? This is enormously valuable
// for scholarship and publicity.
//
// Assessment levels:
//   - "first_known"     — no English edition found in USTC, no english
//                         translation known. High confidence novel.
//   - "likely_first"    — USTC has no English edition, but we can't be
//                         sure no modern translation exists.
//   - "existing_english"— USTC shows English editions exist (or book is
//                         already in English).
//   - "unknown"         — insufficient data to assess.

async function assessFirstTranslation(db, books, dryRun) {
  console.log('\n=== PHASE 3: First-Translation Assessment ===\n');

  let firstKnown = 0, likelyFirst = 0, existingEnglish = 0, unknown = 0, updated = 0;

  // Books that have translations and are NOT in English
  const translatedBooks = books.filter(b => {
    const hasTranslation = (b.pages_translated || 0) > 0;
    const isEnglish = (b.language || '').toLowerCase() === 'english';
    return hasTranslation && !isEnglish;
  });

  console.log(`Books with translations (non-English): ${translatedBooks.length}`);

  for (const book of translatedBooks) {
    const shortTitle = (book.display_title || book.title || '').substring(0, 55);
    const year = book.year || parseInt(book.published) || 0;

    let assessment = 'unknown';
    let reasoning = [];

    // Check USTC catalog_ref for work_type and language info
    const ustcRef = (book.catalog_refs || []).find(r => r.source === 'ustc');
    const bphRef = (book.catalog_refs || []).find(r => r.source === 'bph');

    if (ustcRef) {
      const ustcLang = ustcRef.ustc_language?.toLowerCase() || '';
      const aiEnrichment = ustcRef.ai_enrichment || {};

      // If the USTC record is NOT in English, that's evidence for first translation
      if (ustcLang && ustcLang !== 'english') {
        reasoning.push(`USTC language: ${ustcLang} (not English)`);

        // Check if work_type suggests it's a translation of something else
        if (aiEnrichment.work_type === 'translation') {
          reasoning.push(`USTC work_type: translation (already a translation from ${aiEnrichment.original_author || 'unknown'})`);
        }

        // If year < 1700 and language is Latin/German/etc, likely first English
        if (year > 0 && year < 1700) {
          assessment = 'likely_first';
          reasoning.push(`Pre-1700 ${ustcLang} text — likely no prior English translation`);
        } else {
          assessment = 'likely_first';
          reasoning.push('Non-English USTC record, no English edition found');
        }
      } else if (ustcLang === 'english') {
        assessment = 'existing_english';
        reasoning.push('USTC shows English language edition');
      }
    }

    // Check the AI metadata first_translation field (from enrich-metadata-text.mjs)
    if (book.ai_metadata?.first_translation !== undefined) {
      const aiFirstTrans = book.ai_metadata.first_translation;
      if (aiFirstTrans === true || aiFirstTrans === 'true' || aiFirstTrans === 'likely') {
        if (assessment === 'likely_first') {
          assessment = 'first_known';
          reasoning.push('AI metadata also rates as first translation');
        } else if (assessment === 'unknown') {
          assessment = 'likely_first';
          reasoning.push('AI metadata rates as first translation');
        }
      } else if (aiFirstTrans === false || aiFirstTrans === 'false' || aiFirstTrans === 'no') {
        if (assessment !== 'existing_english') {
          assessment = 'existing_english';
          reasoning.push('AI metadata says English translations exist');
        }
      }
    }

    // English books being "translated" (modernized) are never first translations
    if ((book.language || '').toLowerCase() === 'english') {
      assessment = 'existing_english';
      reasoning = ['Book is already in English (modernization, not translation)'];
    }

    // No translation at all = unknown
    if ((book.pages_translated || 0) === 0) {
      assessment = 'unknown';
      reasoning = ['No translation yet'];
    }

    // If still unknown but has year and non-English language, give it likely_first
    if (assessment === 'unknown' && year > 0 && year < 1700) {
      const lang = (book.language || '').toLowerCase();
      if (lang && lang !== 'english' && lang !== 'unknown') {
        assessment = 'likely_first';
        reasoning.push(`Pre-1700 ${lang} text with no known English translation`);
      }
    }

    const current = book.first_translation_status;
    if (current !== assessment) {
      switch (assessment) {
        case 'first_known': firstKnown++; break;
        case 'likely_first': likelyFirst++; break;
        case 'existing_english': existingEnglish++; break;
        default: unknown++;
      }

      if (assessment !== 'unknown') {
        console.log(`  ${assessment}: ${shortTitle}`);
        console.log(`    ${reasoning.join('; ')}`);
      }

      if (!dryRun) {
        await db.collection('books').updateOne(
          { id: book.id },
          {
            $set: {
              first_translation_status: assessment,
              first_translation_reasoning: reasoning,
              first_translation_assessed_at: new Date(),
              updated_at: new Date(),
            },
          }
        );
        updated++;
      }
    }
  }

  console.log(`\nFirst-translation assessment:`);
  console.log(`  first_known: ${firstKnown}`);
  console.log(`  likely_first: ${likelyFirst}`);
  console.log(`  existing_english: ${existingEnglish}`);
  console.log(`  unknown: ${unknown}`);
  console.log(`  Updated: ${updated}`);

  return { firstKnown, likelyFirst, existingEnglish, unknown, updated };
}

// ── Metadata quality assessment ─────────────────────────────────────

async function assessMetadataQuality(db, books, dryRun) {
  console.log('\n=== PHASE 4: Metadata Quality Assessment ===\n');

  let verified = 0, catalogMatched = 0, aiEnriched = 0, importMeta = 0;
  let aiPartial = 0, suspect = 0, unknown = 0, updated = 0;
  let flaggedForReview = 0;

  for (const book of books) {
    const refs = book.catalog_refs || [];
    const hasHighConfidenceRef = refs.some(r => r.match_confidence === 'high');
    const hasMedConfidenceRef = refs.some(r => r.match_confidence === 'medium' || r.match_confidence === 'high');
    const hasAiMetadata = !!book.ai_metadata?.enriched_at;
    const hasYear = !!book.year;
    const hasLanguage = book.language && book.language !== 'Unknown';
    const hasCategories = (book.categories || []).length > 0;
    const hasAuthor = !!book.author;

    let quality;
    if (hasHighConfidenceRef) {
      quality = 'verified';
      verified++;
    } else if (hasMedConfidenceRef) {
      quality = 'catalog_matched';
      catalogMatched++;
    } else if (hasAiMetadata && hasYear && hasLanguage && hasAuthor) {
      quality = 'ai_enriched';
      aiEnriched++;
    } else if (hasYear && hasLanguage && hasCategories) {
      quality = 'import_metadata';
      importMeta++;
    } else if (hasAiMetadata) {
      quality = 'ai_partial';
      aiPartial++;
    } else if (!hasYear || !hasLanguage) {
      quality = 'suspect';
      suspect++;
    } else {
      quality = 'unknown';
      unknown++;
    }

    // Flag books for curatorial review based on metadata issues
    const reviewReasons = [];
    if (!hasYear) reviewReasons.push('missing_year');
    if (!hasLanguage) reviewReasons.push('missing_language');
    if (!hasAuthor) reviewReasons.push('missing_author');
    if ((book.language || '').toLowerCase() === 'unknown') reviewReasons.push('unknown_language');
    if (!hasCategories && hasAiMetadata) reviewReasons.push('ai_enriched_no_categories');
    if (quality === 'suspect' || quality === 'unknown') reviewReasons.push('suspect_metadata');
    // Books with translations but no USTC match in the right date range
    const year = book.year || parseInt(book.published) || 0;
    if (year >= 1400 && year <= 1700 && !hasMedConfidenceRef && (book.pages_translated || 0) > 0) {
      reviewReasons.push('no_catalog_match');
    }

    const needsReview = reviewReasons.length > 0;
    if (needsReview) flaggedForReview++;

    if (!dryRun) {
      const updates = {};
      if (book.metadata_quality !== quality) updates.metadata_quality = quality;
      if (needsReview && (!book.curatorial_review || book.curatorial_review.status !== 'reviewed')) {
        updates.curatorial_review = {
          status: 'needs_review',
          reasons: reviewReasons,
          flagged_at: new Date(),
          flagged_by: 'enrich-from-catalogs.mjs',
        };
      }

      if (Object.keys(updates).length > 0) {
        updates.updated_at = new Date();
        await db.collection('books').updateOne({ id: book.id }, { $set: updates });
        updated++;
      }
    }
  }

  console.log(`Quality distribution:`);
  console.log(`  verified:         ${verified}`);
  console.log(`  catalog_matched:  ${catalogMatched}`);
  console.log(`  ai_enriched:      ${aiEnriched}`);
  console.log(`  import_metadata:  ${importMeta}`);
  console.log(`  ai_partial:       ${aiPartial}`);
  console.log(`  suspect:          ${suspect}`);
  console.log(`  unknown:          ${unknown}`);
  console.log(`  Flagged for curatorial review: ${flaggedForReview}`);
  console.log(`  Updated:          ${updated}`);

  return { verified, catalogMatched, aiEnriched, importMeta, aiPartial, suspect, unknown, flaggedForReview, updated };
}

// ── Main ─────────────────────────────────────────────────────────────

async function main() {
  const args = process.argv.slice(2);
  const dryRun = !args.includes('--apply');
  const bphOnly = args.includes('--bph-only');
  const ustcOnly = args.includes('--ustc-only');
  const qualityOnly = args.includes('--quality-only');
  const firstTransOnly = args.includes('--first-trans-only');
  const limit = args.includes('--limit') ? parseInt(args[args.indexOf('--limit') + 1]) : 0;
  const specificBook = args.includes('--book') ? args[args.indexOf('--book') + 1] : null;
  const runAll = !bphOnly && !ustcOnly && !qualityOnly && !firstTransOnly;

  const phases = [
    (runAll || bphOnly) && 'BPH',
    (runAll || ustcOnly) && 'USTC',
    (runAll || firstTransOnly) && 'First-Translation',
    (runAll || qualityOnly) && 'Quality',
  ].filter(Boolean);

  console.log(`=== Catalog Enrichment (USTC + BPH) ===`);
  console.log(`Mode: ${dryRun ? 'DRY RUN' : 'APPLYING'}`);
  console.log(`Phases: ${phases.join(', ')}\n`);

  const mongoClient = new MongoClient(MONGODB_URI);
  await mongoClient.connect();
  const db = mongoClient.db(MONGODB_DB);

  const filter = {};
  if (specificBook) {
    filter.$or = [
      { title: { $regex: specificBook, $options: 'i' } },
      { author: { $regex: specificBook, $options: 'i' } },
      { id: specificBook },
    ];
  }

  const projection = {
    id: 1, title: 1, display_title: 1, author: 1, year: 1, published: 1,
    language: 1, categories: 1, ia_identifier: 1, catalog_refs: 1,
    ai_metadata: 1, field_provenance: 1, metadata_quality: 1,
    publication_place: 1, printer: 1, format: 1, english_title: 1,
    pages_translated: 1, pages_ocr: 1, first_translation_status: 1,
  };

  let books = await db.collection('books').find(filter).project(projection).toArray();
  if (limit > 0) books = books.slice(0, limit);
  console.log(`Total books: ${books.length}`);

  async function refreshBooks() {
    books = await db.collection('books').find(filter).project(projection).toArray();
    if (limit > 0) books = books.slice(0, limit);
  }

  // Phase 1: BPH
  if (runAll || bphOnly) {
    await matchBPH(db, books, dryRun);
    if (!dryRun) await refreshBooks();
  }

  // Phase 2: USTC
  if (runAll || ustcOnly) {
    await matchUSTC(db, books, dryRun);
    if (!dryRun) await refreshBooks();
  }

  // Phase 3: First-translation assessment
  if (runAll || firstTransOnly) {
    await assessFirstTranslation(db, books, dryRun);
    if (!dryRun) await refreshBooks();
  }

  // Phase 4: Quality assessment
  if (runAll || qualityOnly) {
    await assessMetadataQuality(db, books, dryRun);
  }

  if (dryRun) console.log('\n(Dry run — use --apply to write to DB.)');
  await mongoClient.close();
}

main().catch(err => { console.error('Fatal error:', err); process.exit(1); });
