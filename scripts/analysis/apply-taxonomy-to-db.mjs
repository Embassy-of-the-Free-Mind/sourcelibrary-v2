#!/usr/bin/env node
/**
 * Apply cluster taxonomy to books in MongoDB.
 *
 * Re-derives sub-cluster assignments from embeddings (deterministic with random_state=42),
 * then writes `taxonomy: { cluster, subcluster }` to each book document.
 *
 * This is a two-phase approach:
 *   Phase 1: Python script generates book_id → cluster/subcluster mapping
 *   Phase 2: This script reads the mapping and writes to MongoDB
 *
 * Usage:
 *   # First generate the mapping:
 *   python3 scripts/analysis/generate-taxonomy-mapping.py
 *   # Then apply to DB:
 *   set -a; source .env.production.local; set +a; node scripts/analysis/apply-taxonomy-to-db.mjs [--dry-run]
 */

import { MongoClient } from 'mongodb';
import { readFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_DIR = join(__dirname, '..', 'output');

async function main() {
  const dryRun = process.argv.includes('--dry-run');

  // Load the taxonomy mapping (generated by Python)
  const mappingPath = join(OUTPUT_DIR, 'taxonomy-mapping.json');
  let mapping;
  try {
    mapping = JSON.parse(readFileSync(mappingPath, 'utf-8'));
  } catch (e) {
    console.error(`Missing ${mappingPath}`);
    console.error('Run: python3 scripts/analysis/generate-taxonomy-mapping.py');
    process.exit(1);
  }

  console.log(`Loaded taxonomy mapping: ${mapping.books.length} books`);
  console.log(`  Clusters: ${mapping.stats.clusters}`);
  console.log(`  Subclusters: ${mapping.stats.subclusters}`);
  console.log(`  Noise (unclustered): ${mapping.stats.noise}\n`);

  if (!process.env.MONGODB_URI) {
    console.error('MONGODB_URI not set');
    process.exit(1);
  }

  const client = new MongoClient(process.env.MONGODB_URI);
  await client.connect();
  const db = client.db('bookstore');
  const books = db.collection('books');

  // Build bulk operations
  const bulkOps = [];

  for (const entry of mapping.books) {
    const taxonomy = {
      cluster: entry.cluster,
      cluster_id: entry.cluster_id,
    };
    if (entry.subcluster) {
      taxonomy.subcluster = entry.subcluster;
      taxonomy.subcluster_idx = entry.subcluster_idx;
    }
    if (entry.probability != null) {
      taxonomy.probability = entry.probability;
    }

    bulkOps.push({
      updateOne: {
        filter: { id: entry.book_id },
        update: { $set: { taxonomy } },
      },
    });
  }

  // Also clear taxonomy from noise books
  for (const bookId of mapping.noise_book_ids || []) {
    bulkOps.push({
      updateOne: {
        filter: { id: bookId },
        update: { $set: { taxonomy: { cluster: null, subcluster: null, noise: true } } },
      },
    });
  }

  console.log(`Prepared ${bulkOps.length} updates`);

  if (dryRun) {
    // Show sample
    console.log('\nSample assignments:');
    for (const entry of mapping.books.slice(0, 15)) {
      const sub = entry.subcluster ? ` → ${entry.subcluster}` : '';
      console.log(`  ${(entry.title || '').substring(0, 60)} | ${entry.cluster}${sub}`);
    }
    console.log('\n[DRY RUN] No changes written.');
    await client.close();
    return;
  }

  // Write in batches
  const BATCH = 500;
  let updated = 0;
  for (let i = 0; i < bulkOps.length; i += BATCH) {
    const batch = bulkOps.slice(i, i + BATCH);
    const result = await books.bulkWrite(batch);
    updated += result.modifiedCount;
    process.stdout.write(`  Written: ${Math.min(i + BATCH, bulkOps.length)}/${bulkOps.length}\r`);
  }
  console.log(`\nUpdated ${updated} books with taxonomy data.`);

  // Summary by cluster
  console.log('\n=== TAXONOMY SUMMARY ===\n');
  const clusterCounts = {};
  for (const entry of mapping.books) {
    const key = entry.cluster;
    clusterCounts[key] = (clusterCounts[key] || 0) + 1;
  }
  const sorted = Object.entries(clusterCounts).sort((a, b) => b[1] - a[1]);
  for (const [name, count] of sorted) {
    console.log(`  ${name}: ${count} books`);
  }

  await client.close();
  console.log('\nDone.');
}

main().catch(e => {
  console.error(e);
  process.exit(1);
});
