#!/usr/bin/env node
/**
 * PRIOR ART: scripts/audit/r2-key-book-scope.mjs — guards the R2 KEY lane (does a page's image URL
 * contain its own book_id?). It does NOT cover this: it returned PASS on all 12 books of the #3391
 * cohort while they served another book's text under another book's title. No existing audit looks at
 * DERIVED metadata, so this is new rather than a duplicate.
 *
 * Audit: metadata DERIVED from page text must describe the book it is attached to (#3362/#3391).
 *
 * THE INVARIANT
 *   `ai_metadata` (and the `display_title` / `year` / `summary` / `chapters` promoted from it) is
 *   generated by reading a book's OCR. If the OCR was another book's text, every derived field
 *   describes the wrong book — confidently, in fluent prose, with no error anywhere.
 *
 * WHY IT MATTERS
 *   In Mar-Apr 2026 a missing book_id sent page images to a shared `archived/undefined/<n>.jpg` key,
 *   so OCR transcribed other books' pages into hundreds of books (#3362). The image lane was repaired
 *   2026-06-01 and the text lane in #3391 — but the enrichment that ran on the poisoned text in
 *   between was never revisited. On 2026-09-07, twelve VISIBLE books (Aldrovandi's Musaeum Metallicum
 *   and Ornithologiae, Fabricius's Opera Chirurgica, Clavius, Averroes, al-Battani, Ulugh Beg,
 *   Libavius x3, al-Farghani) each carried ai_metadata asserting author "Benedictus de Spinoza",
 *   estimated_year 1803, and a description explaining they were the 1803 Jena edition of Spinoza's
 *   collected works. The public citation apparatus emitted that title over Russian prose.
 *
 *   They were found by a human noticing the word "Spinoza", not by any instrument. This is the
 *   instrument.
 *
 * THE TWO SIGNALS
 *   A. TITLE COLLISION. Several books whose OWN titles differ from each other share one AI-derived
 *      display_title. Legitimate duplicate holdings (22 copies of the Consolation of Philosophy) also
 *      share an AI title — but their own titles agree too. Agreement among derived titles combined
 *      with disagreement among real titles is the poisoning shape.
 *   B. YEAR DIVERGENCE. ai_metadata.estimated_year far from the edition year. The cohort above sat at
 *      Δ155 (1803 asserted over a 1648 folio). Benign hits exist — a work composed c.200 CE in a 1950
 *      edition — so this signal is advisory and reported separately.
 *
 * USAGE
 *   set -a; source .env.production.local; set +a
 *   node scripts/audit/derived-metadata-scope.mjs                 # both signals
 *   node scripts/audit/derived-metadata-scope.mjs --min-cluster 3 # signal A sensitivity
 *   node scripts/audit/derived-metadata-scope.mjs --year-delta 75 # signal B sensitivity
 *   node scripts/audit/derived-metadata-scope.mjs --positive-control <backup.jsonl>
 *
 * POSITIVE CONTROL — read this before trusting a clean run.
 *   The repair that motivated this audit DELETED the only known positives, so a clean corpus result
 *   proves nothing on its own ("a probe needs a positive control"). --positive-control replays the
 *   pre-repair ai_metadata from an unpoison-enrich backup JSONL through signal A and asserts it fires.
 *   A clean run WITHOUT a passing positive control is not evidence of absence.
 *
 * Exits non-zero when signal A finds a cluster, so it can gate CI or a cron. READ-ONLY.
 */
import { MongoClient } from 'mongodb';
import fs from 'node:fs';

const args = process.argv.slice(2);
const val = (n, d) => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : d; };
const MIN_CLUSTER = parseInt(val('min-cluster', '3'), 10);
const YEAR_DELTA = parseInt(val('year-delta', '120'), 10);
const PC_PATH = val('positive-control', null);

/**
 * Loose title tokens. MUST be script-aware: an `[^a-z0-9\s]` filter deletes CJK, Greek, Cyrillic,
 * Arabic and Hebrew entirely, leaving an empty token set — and an empty set shares no token with
 * anything, so every volume of one CJK set reads as an unrelated work and the audit reports a
 * 15-book cluster for 三才圖會 vols 6-94. Caught on the first real run of this script.
 * Latin-script words are kept when >3 chars; scripts that do not space-delimit (Han, Kana, Hangul)
 * contribute their individual characters, which is enough for the shared-token test below.
 */
const words = (s) => {
  const cleaned = (s || '').toLowerCase().replace(/[\p{P}\p{S}]/gu, ' ');
  const toks = [];
  for (const w of cleaned.split(/\s+/).filter(Boolean)) {
    if (/[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}]/u.test(w)) {
      toks.push(...[...w].filter((ch) => /[\p{L}\p{N}]/u.test(ch)));
    } else if (w.length > 3 && /[\p{L}\p{N}]/u.test(w)) {
      toks.push(w);
    }
  }
  return toks;
};
const titleKey = (s) => words(s).sort().join(' ');
/** Do two real titles look like the same work? Any shared significant word is enough (deliberately
 *  generous — we want to SUPPRESS clusters, and a false "same work" hides nothing but a true one). */
const sameWork = (a, b) => { const A = new Set(words(a)); return words(b).some((w) => A.has(w)); };

/** Signal A over an array of {id,title,aiTitle}. Returns clusters of mutually-unrelated real titles. */
function findCollisions(rows, minCluster) {
  const byAi = new Map();
  for (const r of rows) {
    if (!r.aiTitle || !r.title) continue;
    const k = titleKey(r.aiTitle);
    if (!k) continue;
    if (!byAi.has(k)) byAi.set(k, []);
    byAi.get(k).push(r);
  }
  const out = [];
  for (const [k, group] of byAi) {
    if (group.length < minCluster) continue;
    // Keep only groups whose REAL titles are mutually dissimilar (distinct works wearing one AI title).
    const distinct = [];
    for (const g of group) if (!distinct.some((d) => sameWork(d.title, g.title))) distinct.push(g);
    if (distinct.length < minCluster) continue;
    // AUTHOR CORROBORATION. Differently-worded editions of ONE work also collide here — "De Civitate
    // Dei" against "La seconde partie de la translacion..." share no title token but are the same
    // book, and that is a false positive, not a finding. What separated the real #3391 cohort was
    // that the DERIVED author was constant ("Benedictus de Spinoza") while the real authors were all
    // different (Aldrovandi, Clavius, Averroes...). Require that shape: derived author agrees with
    // the cluster, real authors do not. When the derived author matches the book's own author, the
    // enrichment read the right book and a shared title is just cataloguing.
    const agreesWithOwnAuthor = group.filter((g) => g.aiAuthor && g.author && sameWork(g.aiAuthor, g.author)).length;
    if (agreesWithOwnAuthor > 0) continue;
    out.push({ key: k, aiTitle: group[0].aiTitle, aiAuthor: group[0].aiAuthor, members: group, distinct: distinct.length });
  }
  return out.sort((a, b) => b.distinct - a.distinct);
}

const client = new MongoClient(process.env.MONGODB_URI);
await client.connect();
try {
  const db = client.db(process.env.MONGODB_DB || 'bookstore');
  if (PC_PATH) {
    // Replay pre-repair ai_metadata, but resolve each book's REAL author from the live document so
    // the author-corroboration branch is actually exercised. The backup stores only the fields that
    // were cleared, and `author` was never poisoned — so without this lookup `author` is undefined,
    // corroboration is skipped, and the control passes through an untested code path.
    const recs = fs.readFileSync(PC_PATH, 'utf8').trim().split('\n').map((l) => JSON.parse(l))
      .filter((r) => r.cleared?.ai_metadata?.display_title);
    const live = await db.collection('books').find(
      { id: { $in: recs.map((r) => r.id) } }, { projection: { id: 1, author: 1 } },
    ).toArray();
    const authorOf = new Map(live.map((b) => [String(b.id), b.author]));
    const rows = recs.map((r) => ({
      id: r.id, title: r.title, author: authorOf.get(String(r.id)),
      aiTitle: r.cleared.ai_metadata.display_title, aiAuthor: r.cleared.ai_metadata.author,
    }));
    const withAuthor = rows.filter((r) => r.author).length;
    const hits = findCollisions(rows, MIN_CLUSTER);
    console.log(`POSITIVE CONTROL — ${PC_PATH}`);
    console.log(`  replayed ${rows.length} pre-repair records (${withAuthor} with a live author, corroboration exercised)`);
    for (const h of hits) console.log(`  FIRED: ${h.distinct} distinct works share "${h.aiTitle}" (ai author: ${h.aiAuthor})`);
    if (!hits.length) {
      console.error('  FAIL — the audit did NOT fire on known-poisoned data. Do not trust a clean run.');
      process.exit(3);
    }
    console.log('  PASS — the audit detects the known cohort.\n');
  }

  const books = await db.collection('books').find(
    { visible: true, 'ai_metadata.display_title': { $exists: true, $ne: null } },
    { projection: { id: 1, title: 1, author: 1, year: 1, 'ai_metadata.display_title': 1, 'ai_metadata.estimated_year': 1, 'ai_metadata.author': 1 } },
  ).toArray();

  const rows = books.map((b) => ({ id: b.id, title: b.title, author: b.author, year: b.year,
    aiTitle: b.ai_metadata?.display_title, aiAuthor: b.ai_metadata?.author,
    aiYear: b.ai_metadata?.estimated_year }));

  console.log(`Checked ${rows.length} visible books carrying ai_metadata.display_title.\n`);

  const clusters = findCollisions(rows, MIN_CLUSTER);
  console.log(`SIGNAL A — one AI title over ${MIN_CLUSTER}+ mutually-unrelated works: ${clusters.length} cluster(s)`);
  for (const c of clusters) {
    console.log(`\n  "${c.aiTitle}" (ai author: ${c.aiAuthor ?? "—"}) — ${c.distinct} distinct works, ${c.members.length} books`);
    for (const m of c.members.slice(0, 15)) console.log(`      ${String(m.id).slice(-8)}  ${(m.title || '').slice(0, 44)}   [author: ${(m.author || '?').slice(0, 22)}]`);
    if (c.members.length > 15) console.log(`      ...and ${c.members.length - 15} more`);
  }

  const num = (v) => { const n = parseInt(String(v ?? '').match(/\d{3,4}/)?.[0], 10); return Number.isFinite(n) ? n : null; };
  const yearHits = rows.map((r) => ({ r, a: num(r.aiYear), b: num(r.year) }))
    .filter((x) => x.a && x.b && Math.abs(x.a - x.b) >= YEAR_DELTA)
    .sort((p, q) => Math.abs(q.a - q.b) - Math.abs(p.a - p.b));
  console.log(`\nSIGNAL B (advisory) — AI year >=${YEAR_DELTA}yrs from edition year: ${yearHits.length}`);
  for (const y of yearHits.slice(0, 20))
    console.log(`      ${String(y.r.id).slice(-8)}  edition=${y.b} ai=${y.a} (Δ${Math.abs(y.a - y.b)})  ${(y.r.title || '').slice(0, 46)}`);
  if (yearHits.length > 20) console.log(`      ...and ${yearHits.length - 20} more`);
  console.log('\n  Signal B alone is not a finding: a work composed c.200 CE in a 1950 edition trips it\n  legitimately. Treat it as a queue to eyeball, and as corroboration for a signal-A cluster.');

  if (clusters.length) {
    console.log(`\nFAIL — ${clusters.length} title-collision cluster(s). Check each against the books' own scans.`);
    process.exit(1);
  }
  console.log('\nPASS — no AI-derived title spans unrelated works.');
  if (!PC_PATH) console.log('NOTE: run with --positive-control <unpoison-enrich-backup.jsonl> before trusting this.');
} finally {
  await client.close();
}
