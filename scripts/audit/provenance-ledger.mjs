#!/usr/bin/env node
/**
 * provenance-ledger.mjs — re-measures every row of the provenance ledger that sat on
 * /ai-partners until #7737 (measured ad hoc on 2026-10-29; no script reproduced it). READ-ONLY.
 * (#4809, #4613, #7673)
 *
 * PRIOR ART: scripts/audit/provenance-coverage.mjs — checks the #4613 record per WRITER on the
 *   newest pages of a window (is today's writer complete?); it does not draw a random sample of
 *   public pages, does not count model naming, rights or catalogue stamps, and does not
 *   cross-check the inference. scripts/audit/scan-provenance-rights.mjs — a rights SCREEN on scan
 *   provenance clusters, not the rights-record coverage. Both reused, not replaced: this calls
 *   missingProvenance() / inferHistoricalGeneration() from scripts/lib/write-provenance.mjs and
 *   isMaintenanceSource() from scripts/eval/lib/revision-source.mjs.
 *
 * ── Rows, and the fields each reads ─────────────────────────────────────────
 *
 * Books: public = visible:true && pages_count>0 (the canonical live filter), all of them.
 *   a  names the holding library    image_source.provider_name | image_source.contributing_library | contributing_library
 *   b  links back to the scan        image_source.source_url ~ ^https?://   (gap broken down by provider;
 *                                    BPH gap joined to Supabase bph_works by sl_book_id for a UBN / ia_url)
 *   g  rights stated by the library, recorded with where it was read
 *                                    image_source.rights_normalized.status ∈ {stated, stated-from-import}
 *                                    AND (manifest_url set OR source ∈ {oai-mets, iiif-manifest, ia-metadata})
 *                                    (also: stated from the importer's stored field; assumed-by-importer;
 *                                    silent = manifest-silent | no-manifest | fetch-failed)
 *   h  any rights record             image_source.rights_normalized exists
 *   i  catalogue cites its source    field_provenance.title / field_provenance.author (#7673 stamps)
 *
 * Pages: a random $sample of pages, kept only if their book is public, until --sample are kept.
 *   c  transcribed pages naming the model     ocr.data non-empty; ocr.model | ocr.engine.model.
 *        Text no model read (imported digital editions, e.g. esukhia-derge-*) is reported apart as
 *        "not model-read; source named", with which of content_hash / edition / licence / source_url
 *        its subdocument records (the Syriac-lane writer standard: scripts/lib/syriac-kraken-lane.mjs).
 *   d  translated pages naming the model      translation.data | translation.text non-empty; translation.model
 *   e  full record                            missingProvenance(field, sub) → no missing AND no
 *        not_recorded markers, with an engine block (gemini-engine/1, or a specialist engine). The #4613
 *        writers went live 2026-09-28T16:21Z; a block whose slots are all `not_recorded` is NOT full.
 *   e+ (#4809 21:40Z) for generated pages without the full record: inferHistoricalGeneration()
 *        → observed / inferred (by rule) / not_recorded (by reason), then cross-checked against
 *        INDEPENDENT clocks: the batch job (ocr|translation.batch_job_id → batch_jobs.id: window
 *        created_at−1h … (completed_at|updated_at)+3d, and model), the page's own page_revisions
 *        (a snapshot at updated_at ±1h, segmented reading vs maintenance; a maintenance revision NEWER
 *        than updated_at = "generated by X, edited by sweep Y"), translate_batch_runs.queue[].id
 *        (non-shadow runs; a queue lists pages GIVEN to a run, so only a write inside its window counts), and prompt_version vs prompt-history (the version must exist by
 *        updated_at; only the lower bound is checkable — pinned old prompts kept running after a new
 *        default, so "superseded" is not evidence). `jobs` carries book ids, not page ids: not a page clock.
 *        Generated pages with no model or no prompt get the neighbour inference (same book, same
 *        source, model/prompt present, updated_at within 1 h; majority), labelled inferred: neighbours.
 *   f  earlier versions kept                  page_revisions.estimatedDocumentCount()
 *
 * Nothing is written. Inference stays computed on read (#4613).
 *
 * Usage:
 *   node --env-file=.env.production.local scripts/audit/provenance-ledger.mjs
 *     --sample=60000      pages kept (default 60000)
 *     --examples=FILE     write up to 5 page ids per contradiction kind (keep it OUT of this public repo)
 *     --json=FILE         machine-readable result
 *     --no-bph            skip the Supabase bph_works join
 *     --no-pages          books only
 * Exit 0 = measured, 2 = could not measure.
 */
import { MongoClient } from 'mongodb';
import { readFileSync, writeFileSync } from 'node:fs';
import { missingProvenance, inferHistoricalGeneration, ENGINE_SCHEMA } from '../lib/write-provenance.mjs';
import { isMaintenanceSource, MAINTENANCE_RE } from '../eval/lib/revision-source.mjs';

const arg = (k, d) => { const m = process.argv.find((a) => a.startsWith(`--${k}=`)); return m ? m.slice(k.length + 3) : d; };
const has = (k) => process.argv.includes(`--${k}`);
const SAMPLE = Number(arg('sample', 60000));
const EXAMPLES = arg('examples', null);
const JSON_OUT = arg('json', null);
const NO_BPH = has('no-bph');
const NO_PAGES = has('no-pages');
if (!process.env.MONGODB_URI) { console.error('MONGODB_URI not set'); process.exit(2); }

const H = 3600e3, D = 86400e3;
const PUBLIC = { visible: true, pages_count: { $gt: 0 } };
const GENERATED = new Set(['ai', 'batch_api', 'pipeline_preview', 'batch_api_recovery', 'realtime_api_sequential', 'AI generated']);
const SPECIALIST = new Set(['kraken', 'bdrc', 'mineru', 'paddle', 'lightonocr']);
const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(1)}%` : 'n/a');
const row = (label, n, d) => console.log(`  ${label.padEnd(64)} ${String(n).padStart(8)} / ${String(d).padEnd(8)} ${pct(n, d)}`);
const out = { measured_at: new Date().toISOString(), books: {}, pages: {} };
const examples = {};
const example = (kind, id) => { const a = (examples[kind] ??= []); if (a.length < 5) a.push(id); };
const toDate = (v) => (v instanceof Date ? v : v ? new Date(v) : null);
const valid = (d) => d && !Number.isNaN(d.getTime());

const client = await MongoClient.connect(process.env.MONGODB_URI);
const db = client.db('bookstore');

try {
  // ── Books ──────────────────────────────────────────────────────────────────
  console.log(`Provenance ledger — measured ${out.measured_at}\n\nBOOKS (public = visible:true && pages_count>0)`);
  const books = await db.collection('books').find(PUBLIC, { projection: {
    id: 1, contributing_library: 1, 'image_source.provider': 1, 'image_source.provider_name': 1,
    'image_source.contributing_library': 1, 'image_source.source_url': 1, 'image_source.rights_normalized.status': 1,
    'image_source.rights_normalized.source': 1, 'image_source.rights_normalized.manifest_url': 1,
    'field_provenance.title': 1, 'field_provenance.author': 1,
  } }).toArray();
  const N = books.length;
  const publicIds = new Set(books.map((b) => b.id));
  const nonEmpty = (v) => typeof v === 'string' && v.trim().length > 0;
  const noLib = books.filter((b) => !(nonEmpty(b.image_source?.provider_name) || nonEmpty(b.image_source?.contributing_library) || nonEmpty(b.contributing_library)));
  row('a  names the holding library', N - noLib.length, N);
  if (noLib.length && noLib.length <= 10) for (const b of noLib) console.log(`       no library: ${b.id} https://sourcelibrary.org/book/${b.id} (provider ${b.image_source?.provider ?? 'none'})`);

  const noLink = books.filter((b) => !/^https?:\/\//.test(b.image_source?.source_url || ''));
  row('b  links back to the original scan (image_source.source_url)', N - noLink.length, N);
  const gapBy = {};
  for (const b of noLink) gapBy[b.image_source?.provider ?? 'none'] = (gapBy[b.image_source?.provider ?? 'none'] || 0) + 1;
  console.log(`       gap by provider: ${Object.entries(gapBy).sort((x, y) => y[1] - x[1]).map(([k, v]) => `${k} ${v}`).join(', ')}`);

  let bph = null;
  const bphGap = noLink.filter((b) => b.image_source?.provider === 'bph');
  if (!NO_BPH && bphGap.length) {
    const { createClient } = await import('@supabase/supabase-js');
    const sb = createClient(process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_ANON_KEY);
    const rows = [];
    for (let from = 0; ; from += 1000) { // supabase-js caps every response at 1,000 rows
      const { data, error } = await sb.from('bph_works').select('ubn, sl_book_id, ia_url').not('sl_book_id', 'is', null).is('deleted_at', null).range(from, from + 999);
      if (error) throw new Error(`bph_works: ${error.message}`);
      rows.push(...data); if (data.length < 1000) break;
    }
    const byBook = new Map(rows.map((r) => [r.sl_book_id, r]));
    const matched = bphGap.filter((b) => byBook.has(b.id));
    bph = { gap: bphGap.length, with_ubn: matched.filter((b) => byBook.get(b.id).ubn).length, with_ia_url: matched.filter((b) => /^https?:/.test(byBook.get(b.id).ia_url || '')).length };
    console.log(`       BPH gap ${bph.gap}: ${bph.with_ubn} have a bph_works row with a UBN (our BPH catalogue record, /catalog/<ubn>); ${bph.with_ia_url} also carry an ia_url. bph_works has no external catalogue URL column.`);
  }

  const rs = (b) => b.image_source?.rights_normalized;
  const READ_FROM = new Set(['oai-mets', 'iiif-manifest', 'ia-metadata']);
  const gRead = books.filter((b) => ['stated', 'stated-from-import'].includes(rs(b)?.status) && (rs(b).manifest_url || READ_FROM.has(rs(b).source))).length;
  const gImporter = books.filter((b) => rs(b)?.status === 'stated' && !(rs(b).manifest_url || READ_FROM.has(rs(b).source))).length;
  const gAssumed = books.filter((b) => rs(b)?.status === 'assumed-by-importer').length;
  const gSilent = books.filter((b) => ['manifest-silent', 'no-manifest', 'fetch-failed'].includes(rs(b)?.status)).length;
  const gAny = books.filter((b) => rs(b)).length;
  row('g  rights stated by the library, with where it was read', gRead, N);
  row('     stated in the importer\'s stored field (no read location)', gImporter, N);
  row('     assumed by importer', gAssumed, N);
  row('     silent / no manifest / fetch failed', gSilent, N);
  row('h  any rights record', gAny, N);
  const silentBy = {};
  for (const b of books) { const s = rs(b)?.status; if (['manifest-silent', 'no-manifest', 'fetch-failed'].includes(s)) { const k = `${b.image_source?.provider}:${s}`; silentBy[k] = (silentBy[k] || 0) + 1; } }
  console.log(`       silent by provider: ${Object.entries(silentBy).sort((x, y) => y[1] - x[1]).slice(0, 12).map(([k, v]) => `${k} ${v}`).join(', ')}`);

  const fp = (b) => b.field_provenance || {};
  const iTitle = books.filter((b) => fp(b).title).length, iAuthor = books.filter((b) => fp(b).author).length;
  const iBoth = books.filter((b) => fp(b).title && fp(b).author).length, iEither = books.filter((b) => fp(b).title || fp(b).author).length;
  row('i  catalogue cites its source: title stamped', iTitle, N);
  row('     author stamped', iAuthor, N);
  row('     title AND author', iBoth, N);
  row('     title OR author', iEither, N);
  Object.assign(out.books, { public: N, a: N - noLib.length, a_missing: noLib.map((b) => b.id), b: N - noLink.length, b_gap_by_provider: gapBy, bph, g_read: gRead, g_importer_field: gImporter, g_assumed: gAssumed, g_silent: gSilent, g_silent_by: silentBy, h: gAny, i_title: iTitle, i_author: iAuthor, i_both: iBoth, i_either: iEither });

  const revCount = await db.collection('page_revisions').estimatedDocumentCount();
  console.log(`\nf  earlier page versions kept (page_revisions, estimated): ${revCount.toLocaleString('en-US')}`);
  out.pages.f = revCount;

  if (!NO_PAGES) await measurePages(publicIds);
} catch (e) {
  console.error(e); await client.close(); process.exit(2);
}
if (EXAMPLES) { writeFileSync(EXAMPLES, JSON.stringify(examples, null, 2)); console.log(`\nexamples (≤5 per kind): ${EXAMPLES}`); }
if (JSON_OUT) writeFileSync(JSON_OUT, JSON.stringify({ ...out, example_kinds: Object.keys(examples) }, null, 2));
await client.close();

// ── Pages ────────────────────────────────────────────────────────────────────
async function measurePages(publicIds) {
  const pages = db.collection('pages');
  const sub = (f) => ({ $let: { vars: { s: `$${f}` }, in: { $cond: [{ $eq: [{ $type: '$$s' }, 'object'] }, { $arrayToObject: { $filter: { input: { $objectToArray: '$$s' }, cond: { $not: { $in: ['$$this.k', ['data', 'text']] } } } } }, null] } } });
  const hasText = (f, keys) => ({ $or: keys.map((k) => ({ $gt: [{ $strLenCP: { $cond: [{ $eq: [{ $type: `$${f}.${k}` }, 'string'] }, `$${f}.${k}`, ''] } }, 0] })) });
  const kept = [];
  let drawn = 0;
  for (let round = 0; kept.length < SAMPLE && round < 6; round++) {
    const want = Math.ceil((SAMPLE - kept.length) * 1.6) + 1000;
    const batch = await pages.aggregate([{ $sample: { size: want } }, { $project: { id: 1, book_id: 1, ocr: sub('ocr'), translation: sub('translation'), has_ocr: hasText('ocr', ['data']), has_tr: hasText('translation', ['data', 'text']) } }], { allowDiskUse: true }).toArray();
    drawn += batch.length;
    const seen = new Set(kept.map((p) => String(p._id)));
    for (const p of batch) if (publicIds.has(p.book_id) && !seen.has(String(p._id)) && kept.length < SAMPLE) { kept.push(p); seen.add(String(p._id)); }
  }
  console.log(`\nPAGES — random $sample: ${drawn.toLocaleString('en-US')} drawn, ${kept.length.toLocaleString('en-US')} of public books kept`);
  out.pages.sample = kept.length;
  if (kept.length < SAMPLE * 0.9) throw new Error(`sample short: ${kept.length}`);

  // independent records, fetched once for the whole sample
  const ids = kept.map((p) => p.id || String(p._id));
  const revs = new Map();
  for (let i = 0; i < ids.length; i += 1000) {
    const rows = await db.collection('page_revisions').find({ page_id: { $in: ids.slice(i, i + 1000) }, field: { $in: ['ocr', 'translation'] } }, { projection: { page_id: 1, field: 1, source: 1, reason: 1, run_id: 1, created_at: 1, original_date: 1 } }).toArray();
    for (const r of rows) { const k = `${r.page_id}|${r.field}`; (revs.get(k) ?? revs.set(k, []).get(k)).push(r); }
  }
  const jobIds = new Set();
  for (const p of kept) for (const f of ['ocr', 'translation']) { const j = p[f]?.batch_job_id || p[f]?.engine?.run?.batch_job_id; if (j) jobIds.add(j); }
  const jobs = new Map();
  const jl = [...jobIds];
  // our nanoid (`id`), or the Gemini batch name (`batches/…`) that newer writers stamp in engine.run.batch_job_id
  for (let i = 0; i < jl.length; i += 5000) {
    const chunk = jl.slice(i, i + 5000);
    for (const j of await db.collection('batch_jobs').find({ $or: [{ id: { $in: chunk } }, { job_name: { $in: chunk } }, { gemini_job_name: { $in: chunk } }] }, { projection: { id: 1, job_name: 1, gemini_job_name: 1, type: 1, model: 1, created_at: 1, completed_at: 1, updated_at: 1 } }).toArray())
      for (const k of [j.id, j.job_name, j.gemini_job_name]) if (k) jobs.set(k, j);
  }
  const trPages = kept.filter((p) => p.has_tr).map((p) => p.id || String(p._id));
  const runs = new Map();
  for (let i = 0; i < trPages.length; i += 5000) {
    const chunk = new Set(trPages.slice(i, i + 5000));
    for (const r of await db.collection('translate_batch_runs').find({ 'queue.id': { $in: [...chunk] }, shadow: { $ne: true } }, { projection: { id: 1, model: 1, created_at: 1, updated_at: 1, completed_at: 1, 'queue.id': 1 } }).toArray())
      for (const q of r.queue || []) if (chunk.has(q.id)) (runs.get(q.id) ?? runs.set(q.id, []).get(q.id)).push(r);
  }
  console.log(`  independent records: ${revs.size} page×field revision chains, ${jl.filter((k) => jobs.has(k)).length}/${jobIds.size} batch jobs found, ${runs.size} pages in translate_batch_runs`);

  const promptBirth = promptBirthResolver();

  for (const field of ['ocr', 'translation']) {
    const label = field === 'ocr' ? 'c  transcribed pages' : 'd  translated pages';
    const withText = kept.filter((p) => (field === 'ocr' ? p.has_ocr : p.has_tr));
    const model = (s) => s?.model || s?.engine?.model;
    const named = withText.filter((p) => model(p[field]));
    const imported = withText.filter((p) => !model(p[field]) && p[field]?.source && !GENERATED.has(p[field].source));
    const genNoModel = withText.filter((p) => !model(p[field]) && GENERATED.has(p[field]?.source));
    const unknown = withText.filter((p) => !model(p[field]) && !p[field]?.source);
    console.log(`\n${label} (${field}) — ${withText.length} pages with text`);
    row(`${label.slice(0, 2)} name the model`, named.length, withText.length);
    row('     not model-read; source named (imported text)', imported.length, withText.length);
    row('     model named OR imported with source named', named.length + imported.length, withText.length);
    row('     generated source, no model', genNoModel.length, withText.length);
    row('     no model, no source (unknown)', unknown.length, withText.length);
    const impBy = {};
    for (const p of imported) {
      const s = p[field];
      const k = s.source;
      const e = (impBy[k] ??= { n: 0, content_hash: 0, edition: 0, licence: 0, source_url: 0 });
      const j = JSON.stringify(s); // the whole subdocument (text excluded): esukhia nests these under text_edition
      e.n++; if (/^[0-9a-f]{16,64}$/.test(s.content_hash || '')) e.content_hash++;
      if (/"[a-z_]*edition[a-z_]*":\s*\{?"?[^"]/i.test(j)) e.edition++; if (/"licen[cs]e":\s*"[^"]/i.test(j)) e.licence++; if (/":\s*"https?:\/\//.test(j)) e.source_url++;
    }
    if (imported.length) console.log(`       imported by source (n · content_hash · edition · licence · url): ${Object.entries(impBy).sort((x, y) => y[1].n - x[1].n).slice(0, 10).map(([k, v]) => `${k} ${v.n}·${v.content_hash}·${v.edition}·${v.licence}·${v.source_url}`).join(', ')}`);

    // e — full record
    const full = [], partial = [], none = [];
    for (const p of withText) {
      const s = p[field];
      const { missing, markers } = missingProvenance(field, s);
      const engineOk = s?.engine && typeof s.engine === 'object' && (s.engine.schema === ENGINE_SCHEMA || SPECIALIST.has(s.source));
      if (engineOk && !missing.length && !markers.length) full.push(p);
      else if (s?.engine && typeof s.engine === 'object') partial.push(p);
      else none.push(p);
    }
    row(`e  full record (${field})`, full.length, withText.length);
    row('     engine block with gaps or not_recorded markers', partial.length, withText.length);
    row('     no engine block', none.length, withText.length);

    // e+ — inference and corroboration on generated pages without the full record
    const fullSet = new Set(full);
    const gen = withText.filter((p) => !fullSet.has(p) && GENERATED.has(p[field]?.source));
    const g = { n: gen.length, inferred: {}, not_recorded: {}, checks: {}, grades: { 'inferred+corroborated': 0, 'inferred-only': 0, contradicted: 0, 'not_recorded+corroborated': 0, 'not_recorded': 0 }, edited_by_sweep: {}, edited_any: 0 };
    const check = (name, agree) => { const c = (g.checks[name] ??= { checked: 0, agree: 0 }); c.checked++; if (agree) c.agree++; };
    for (const p of gen) {
      const s = p[field];
      const pid = p.id || String(p._id);
      const engineAllMarkers = s.engine && s.engine.schema === ENGINE_SCHEMA && missingProvenance(field, s).markers.length > 0;
      const inf = inferHistoricalGeneration(field, engineAllMarkers ? { ...s, engine: undefined } : s);
      if (inf.status === 'inferred') g.inferred[inf.rule] = (g.inferred[inf.rule] || 0) + 1;
      else { const r = String(inf.reason || inf.status).replace(/ at \d{4}-.*$/, '').replace(/source=\S+/, 'source=…'); g.not_recorded[r] = (g.not_recorded[r] || 0) + 1; }
      const t = toDate(s.updated_at);
      let corroborated = false; const contradictions = [];
      // batch job
      const jid = s.batch_job_id || s.engine?.run?.batch_job_id;
      const job = jid && jobs.get(jid);
      if (job && valid(t)) {
        const start = toDate(job.created_at), end = toDate(job.completed_at) || toDate(job.updated_at);
        const inWin = valid(start) && t >= new Date(start - H) && (!valid(end) || t <= new Date(+end + 3 * D));
        check('batch job window contains updated_at', inWin);
        if (inWin) corroborated = true;
        else if (valid(start) && t < new Date(start - H)) contradictions.push('updated_at-before-its-batch-job');
        if (job.model && model(s)) { const ok = job.model === model(s); check('batch job model = page model', ok); if (!ok) contradictions.push('model-differs-from-batch-job'); }
      } else if (jid) check('batch job row found', false);
      // translate_batch_runs
      if (field === 'translation' && runs.has(pid) && valid(t)) {
        const rr = runs.get(pid);
        const inWin = rr.some((r) => { const a = toDate(r.created_at) || r._id.getTimestamp(); const b = toDate(r.completed_at) || toDate(r.updated_at); return t >= new Date(a - H) && (!valid(b) || t <= new Date(+b + D)); });
        // A queue lists the pages a run was GIVEN; dropped/excluded/skipped pages stay in it. Outside the window means
        // the run did not write this text (not a contradiction) — only a write inside the window is a clock.
        check('translate_batch_run: queued page written inside the run window', inWin);
        if (inWin) { corroborated = true; if (model(s)) { const ok = rr.some((r) => r.model === model(s)); check('translate_batch_run model = page model (written in window)', ok); if (!ok) contradictions.push('model-differs-from-translate-run'); } }
      }
      // page_revisions
      const chain = revs.get(`${pid}|${field}`) || [];
      if (valid(t) && chain.length) {
        for (const r of chain) { const ca = toDate(r.created_at); if (valid(ca)) check('revision ObjectId time = created_at (±1h)', Math.abs(r._id.getTimestamp() - ca) <= H); }
        const isMaint = (r) => isMaintenanceSource(r.source) || MAINTENANCE_RE.test(r.reason || '') || MAINTENANCE_RE.test(r.run_id || '');
        const at = chain.filter((r) => valid(toDate(r.created_at)) && Math.abs(toDate(r.created_at) - t) <= H);
        if (at.length) {
          const maintAt = at.filter(isMaint);
          check('a revision snapshot at updated_at (±1h) is a reading, not a sweep', maintAt.length < at.length);
          if (maintAt.length === at.length) contradictions.push('updated_at-is-a-sweep-clock'); else corroborated = true;
        }
        const newer = chain.filter((r) => valid(toDate(r.created_at)) && toDate(r.created_at) - t > H && isMaint(r));
        if (newer.length) { g.edited_any++; const lab = String(newer[0].source || newer[0].run_id || newer[0].reason).replace(/[-_]?\d{4}[-\d]*$/, '').replace(/-\d+$/, '') || 'unlabelled'; g.edited_by_sweep[lab] = (g.edited_by_sweep[lab] || 0) + 1; example(`${field}:edited-by-sweep-after-stamp`, pid); }
      }
      // prompt version existed by updated_at
      const birth = promptBirth(field, s);
      if (birth && valid(t)) { const ok = t >= new Date(+birth.at - D); check(`prompt version existed by updated_at (${birth.by})`, ok); if (!ok) contradictions.push(`prompt-version-not-yet-created(${birth.by})`); }
      for (const c of contradictions) example(`${field}:${c}`, pid);
      if (contradictions.length) { g.grades.contradicted++; for (const c of contradictions) g.checks[`CONTRADICTION ${c}`] = { n: (g.checks[`CONTRADICTION ${c}`]?.n || 0) + 1 }; }
      else if (inf.status === 'inferred') g.grades[corroborated ? 'inferred+corroborated' : 'inferred-only']++;
      else g.grades[corroborated ? 'not_recorded+corroborated' : 'not_recorded']++;
    }
    console.log(`  e+ generated pages without the full record: ${g.n}`);
    console.log(`     inferHistoricalGeneration: inferred ${Object.values(g.inferred).reduce((a, b) => a + b, 0)} (${Object.entries(g.inferred).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${v}`).join(', ')})`);
    console.log(`       not_recorded ${Object.values(g.not_recorded).reduce((a, b) => a + b, 0)}: ${Object.entries(g.not_recorded).sort((a, b) => b[1] - a[1]).slice(0, 6).map(([k, v]) => `${v}× ${k}`).join(' | ')}`);
    for (const [k, v] of Object.entries(g.checks)) console.log(`     ${k.padEnd(70)} ${v.n != null ? v.n : `${v.agree}/${v.checked} ${pct(v.agree, v.checked)}`}`);
    for (const [k, v] of Object.entries(g.grades)) row(`     grade: ${k}`, v, g.n);
    row('     grade: generated by X, edited by sweep Y (maintenance revision newer than updated_at)', g.edited_any, g.n);
    console.log(`       by sweep: ${Object.entries(g.edited_by_sweep).sort((a, b) => b[1] - a[1]).slice(0, 8).map(([k, v]) => `${k} ${v}`).join(', ')}`);

    // neighbour inference for generated pages missing a model or a prompt
    const gaps = withText.filter((p) => GENERATED.has(p[field]?.source) && (!model(p[field]) || !p[field]?.prompt_version));
    let nbModel = 0, nbPrompt = 0, nbNone = 0;
    for (const p of gaps) {
      const t = toDate(p[field].updated_at);
      if (!valid(t)) { nbNone++; continue; }
      const nb = await pages.find({ book_id: p.book_id, [`${field}.source`]: p[field].source, [`${field}.updated_at`]: { $gte: new Date(t - H), $lte: new Date(+t + H) }, _id: { $ne: p._id } }, { projection: { [`${field}.model`]: 1, [`${field}.prompt_version`]: 1 } }).limit(50).toArray();
      const maj = (k) => { const c = {}; for (const n of nb) { const v = n[field]?.[k]; if (v) c[v] = (c[v] || 0) + 1; } return Object.entries(c).sort((a, b) => b[1] - a[1])[0]?.[0]; };
      const m = !model(p[field]) && maj('model'), pv = !p[field].prompt_version && maj('prompt_version');
      if (m) nbModel++; if (pv) nbPrompt++; if (!m && !pv) nbNone++;
    }
    console.log(`     neighbour inference (same book+source, ±1h): ${gaps.length} generated pages missing model or prompt → model inferred ${nbModel}, prompt inferred ${nbPrompt}, no neighbour ${nbNone}`);

    // prompt reconstruction estimate (3c): pages without the full record whose prompt resolves to stored text
    const noFull = withText.filter((p) => !fullSet.has(p) && GENERATED.has(p[field]?.source));
    const rec = { prompt_id: 0, prompt_hash: 0, 'name+version': 0, 'dated-label': 0, unresolved: 0 };
    for (const p of noFull) { const b = promptBirth(field, p[field]); rec[b ? b.by : 'unresolved']++; }
    console.log(`     prompt text reconstructable (generated, no full record ${noFull.length}): by prompt_id ${rec.prompt_id}, by prompt_hash ${rec.prompt_hash}, by name+version label ${rec['name+version']}; dated code label (label ≠ text sent) ${rec['dated-label']}; unresolved ${rec.unresolved}`);

    out.pages[field] = { with_text: withText.length, named: named.length, imported: imported.length, imported_by: impBy, generated_no_model: genNoModel.length, unknown: unknown.length, full: full.length, partial: partial.length, no_engine: none.length, inference: g, neighbours: { gaps: gaps.length, model: nbModel, prompt: nbPrompt, none: nbNone }, prompt_reconstruction: rec };
  }
}

/** When did a page's prompt version first exist? prompt-history.json (prompts rows, created_at). */
function promptBirthResolver() {
  const ph = JSON.parse(readFileSync(new URL('../eval/results/prompt-history/prompt-history.json', import.meta.url), 'utf8'));
  const rows = ph.prompts.filter((p) => ['ocr', 'translation', 'english_modernization'].includes(p.type) && p.created_at);
  const byId = new Map(), byHash = new Map(), byNameVer = new Map();
  const earliest = (m, k, at) => { if (!m.has(k) || at < m.get(k)) m.set(k, at); };
  for (const p of rows) {
    const at = new Date(p.created_at);
    byId.set(String(p._id), at);
    for (const h of [p.content_hash, p.content_md5, p.content_hash_stored]) if (h) earliest(byHash, h, at);
    earliest(byNameVer, `${p.name}|${p.version}`, at);
  }
  return (field, s) => {
    if (!s) return null;
    if (s.prompt_id && byId.has(String(s.prompt_id))) return { at: byId.get(String(s.prompt_id)), by: 'prompt_id' };
    if (s.prompt_hash && byHash.has(s.prompt_hash)) return { at: byHash.get(s.prompt_hash), by: 'prompt_hash' };
    const v = String(s.prompt_version ?? '');
    const num = v.match(/^v?(\d+(?:\.\d+)?)$/);
    if (num) { const name = s.prompt_name || (field === 'ocr' ? 'Standard OCR' : 'Standard Translation'); const at = byNameVer.get(`${name}|${num[1]}`); if (at) return { at, by: 'name+version' }; }
    const dated = v.match(/^v[\d.]+\.(\d{4})-(\d{2})$/);
    if (dated) return { at: new Date(`${dated[1]}-${dated[2]}-01T00:00:00Z`), by: 'dated-label' };
    return null;
  };
}
