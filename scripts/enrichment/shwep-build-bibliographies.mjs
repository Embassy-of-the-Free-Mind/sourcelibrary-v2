#!/usr/bin/env node
/**
 * Build display-ready episode bibliographies for the SHWEP Reading Room.
 *
 * Reads the scraped reading lists (src/data/shwep-reading-lists.json — gitignored,
 * the raw scrape from shwep.net) and strips the trailing website cruft (the "Themes"
 * tag block and the members-only "Comments" section), leaving Earl Fontainelle's
 * "Works Cited / Primary / Secondary / Recommended Reading" bibliography.
 *
 * Writes src/data/shwep-bibliographies.ts (committed) — episode number → markdown,
 * rendered at the top of each /shwep/[number] page above the in-library book links.
 *
 * Re-run after re-scraping: node scripts/enrichment/shwep-build-bibliographies.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_DIR = path.join(__dirname, '..', '..', 'src', 'data');

// Boundaries where the bibliography ends and website chrome begins.
const CUT_MARKERS = ['### Themes', '### Comments', 'Comments are open to SHWEP', '\nThemes\n'];

function clean(raw) {
  if (!raw) return '';
  let s = raw;
  let idx = s.length;
  for (const c of CUT_MARKERS) {
    const i = s.indexOf(c);
    if (i >= 0 && i < idx) idx = i;
  }
  s = s.slice(0, idx);
  return s
    .replace(/\n?\[truncated\]\s*$/i, '')   // drop scraper truncation marker
    .replace(/[ \t]+\n/g, '\n')             // trailing whitespace per line
    .replace(/\n{3,}/g, '\n\n')             // collapse blank runs
    .trim();
}

function main() {
  const jsonPath = path.join(DATA_DIR, 'shwep-reading-lists.json');
  if (!fs.existsSync(jsonPath)) {
    console.error(`Missing ${jsonPath} (gitignored — copy it from the main checkout into the worktree first).`);
    process.exit(1);
  }
  const raw = JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));

  const bibs = {};
  let kept = 0, dropped = 0;
  for (const [num, text] of Object.entries(raw)) {
    const c = clean(text);
    if (c.length >= 40) { bibs[num] = c; kept++; }
    else dropped++;
  }

  const sorted = Object.entries(bibs).sort((a, b) => parseInt(a[0]) - parseInt(b[0]));
  let out = `/**
 * Per-episode reading lists for the SHWEP Reading Room — Earl Fontainelle's
 * "Works Cited / Recommended Reading" bibliographies, scraped from each episode
 * page on shwep.net and stripped of site chrome (Themes tags, Comments section).
 *
 * Generated by scripts/enrichment/shwep-build-bibliographies.mjs — do not edit by hand.
 * Rendered (as markdown) at the top of /shwep/[number], credited to SHWEP with a
 * link back to the source episode.
 */
export const SHWEP_BIBLIOGRAPHIES: Record<number, string> = {\n`;
  for (const [num, text] of sorted) {
    const escaped = text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
    out += `  ${num}: \`${escaped}\`,\n`;
  }
  out += `};\n`;
  fs.writeFileSync(path.join(DATA_DIR, 'shwep-bibliographies.ts'), out);

  console.log(`Wrote src/data/shwep-bibliographies.ts — ${kept} bibliographies (${dropped} skipped: too short / none).`);
}

main();
