#!/usr/bin/env node
/**
 * Two facts the SHWEP episode pages need and the book records cannot supply.
 *
 * 1. --languages : the language each cited WORK was composed in.
 *    Book records cannot answer this — `text_role` is 'original' on Latin
 *    renderings of Greek works and `original_language` is absent or wrong (a Greek
 *    De mysteriis records original_language: Latin). Without it the page badges a
 *    1497 Ficino Latin as an authoritative "editio princeps", calls Jonson's own
 *    English a "translation", and offers du Ryer's French as the Qur'an.
 *
 * 2. --notes : why each work is cited in each episode.
 *    Earl Fontainelle's bibliography says "Malalas on the mountebank Ioannes
 *    Isthmeos ... p. 323". Stripped of that, an entry for a Byzantine chronicle on
 *    an alchemy episode looks like a bad match. The note is compressed from his
 *    prose, not invented.
 *
 * Usage:
 *   node scripts/enrichment/shwep-work-facts.mjs --languages
 *   node scripts/enrichment/shwep-work-facts.mjs --notes [--limit=20]
 */
import fs from 'node:fs';
import path from 'node:path';

const MODEL = 'gemini-3.1-flash-lite';
const KEY = process.env.GEMINI_API_KEY_3 || process.env.GEMINI_API_KEY;
if (!KEY) { console.error('Set GEMINI_API_KEY'); process.exit(1); }

const ROOT = process.cwd();
const argv = process.argv.slice(2);
const has = f => argv.includes(f);
const num = (f, d) => { const a = argv.find(x => x.startsWith(f + '=')); return a ? parseInt(a.split('=')[1]) : d; };

/**
 * Read a `export const X = <object literal>;` data file without importing TS.
 * The bibliographies file uses bare numeric keys (`274: "..."`), which is valid TS
 * and invalid JSON, so quote them before parsing.
 */
function readTsData(file, marker) {
  const s = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const start = s.indexOf(marker) + marker.length;
  let body = s.slice(start).trim();
  if (body.endsWith(';')) body = body.slice(0, -1);
  return JSON.parse(
    body
      .replace(/^(\s*)(\d+):/gm, '$1"$2":')   // bare numeric keys
      .replace(/,(\s*[}\]])/g, '$1')          // trailing commas
  );
}

async function gemini(prompt) {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent?key=${KEY}`;
  for (let attempt = 0; attempt < 4; attempt++) {
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }],
        generationConfig: { temperature: 0, responseMimeType: 'application/json' },
      }),
    });
    if (res.status === 429 || res.status >= 500) {
      await new Promise(r => setTimeout(r, 2000 * (attempt + 1)));
      continue;
    }
    if (!res.ok) throw new Error(`${res.status} ${(await res.text()).slice(0, 200)}`);
    const j = await res.json();
    const text = j.candidates?.[0]?.content?.parts?.map(p => p.text).join('') || '';
    if (!text) { await new Promise(r => setTimeout(r, 1500)); continue; }
    return JSON.parse(text);
  }
  throw new Error('gemini: exhausted retries');
}

async function runLanguages() {
  const works = readTsData('src/data/shwep-cited-works.ts', 'SHWEP_CITED_WORKS: ShwepCitedWork[] = ');
  const out = {};
  const BATCH = 40;
  for (let i = 0; i < works.length; i += BATCH) {
    const slice = works.slice(i, i + BATCH);
    const prompt = `For each historical work below, give the language it was ORIGINALLY COMPOSED IN.

Rules:
- Answer with the composition language, never the language of a later edition or translation.
  Iamblichus' De mysteriis is Greek even though most printings are Latin.
  Ben Jonson's The Alchemist is English. The Qur'an is Arabic.
- For a work compiled in several languages or of disputed origin, give the predominant one.
- If you genuinely do not know the work, use "Unknown". Do not guess.
- Use plain English language names: Greek, Latin, Arabic, Hebrew, Sanskrit, English, ...

Return JSON: [{"i": <index>, "language": "<language>"}]

${slice.map((w, n) => `${n}. ${w.author || 'Anonymous'} — ${w.work} (${w.era})`).join('\n')}`;
    const res = await gemini(prompt);
    for (const r of res) {
      const w = slice[r.i];
      if (w && r.language) out[`${w.author}|${w.work}`] = r.language;
    }
    console.log(`languages: ${Math.min(i + BATCH, works.length)}/${works.length}`);
  }
  const file = `/**
 * Language each SHWEP-cited work was COMPOSED in — not the language of any edition
 * we hold. Book records cannot supply this (text_role is 'original' on Latin
 * renderings of Greek works), and without it the episode pages mislabel a
 * translation as the text. Keyed "author|work".
 * Generated by scripts/enrichment/shwep-work-facts.mjs --languages (${MODEL}).
 */
export const SHWEP_WORK_LANGUAGES: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
  fs.writeFileSync(path.join(ROOT, 'src/data/shwep-work-languages.ts'), file);
  console.log(`wrote ${Object.keys(out).length} work languages`);
}

async function runNotes() {
  const works = readTsData('src/data/shwep-cited-works.ts', 'SHWEP_CITED_WORKS: ShwepCitedWork[] = ');
  const bibs = readTsData('src/data/shwep-linked-bibliographies.ts', 'SHWEP_LINKED_BIBLIOGRAPHIES: Record<number, string> = ');

  const byEpisode = new Map();
  for (const w of works) for (const ep of w.episodes) {
    if (!byEpisode.has(ep)) byEpisode.set(ep, []);
    byEpisode.get(ep).push(w);
  }

  const episodes = [...byEpisode.keys()].filter(ep => bibs[ep]).sort((a, b) => a - b);
  const limit = num('--limit', episodes.length);
  const out = {};
  let done = 0;
  for (const ep of episodes.slice(0, limit)) {
    const list = byEpisode.get(ep);
    const prompt = `Below is a podcast episode's works-cited section, then a list of works cited in it.

For each listed work, write ONE short note (max 22 words) saying what the episode cites it FOR,
drawn ONLY from the works-cited text. Keep the citation locus if given (e.g. "p. 323", "frr. 153-4",
"de myst. 5.83"). Do not invent detail. If the text says nothing beyond naming the work, return "".

Return JSON: [{"i": <index>, "note": "<note>"}]

--- WORKS CITED TEXT ---
${String(bibs[ep]).slice(0, 12000)}

--- WORKS ---
${list.map((w, n) => `${n}. ${w.author || 'Anonymous'} — ${w.work}`).join('\n')}`;
    try {
      const res = await gemini(prompt);
      for (const r of res) {
        const w = list[r.i];
        if (w && r.note) out[`${ep}|${w.author}|${w.work}`] = String(r.note).trim();
      }
    } catch (e) {
      console.error(`ep ${ep}: ${e.message}`);
    }
    if (++done % 20 === 0) console.log(`notes: ${done}/${Math.min(limit, episodes.length)} episodes`);
  }
  const file = `/**
 * Why each work is cited in each episode, compressed from Earl Fontainelle's own
 * works-cited prose (never invented). Keyed "episode|author|work". Without these the
 * bibliography entries read as arbitrary — a Jacobean comedy on a Byzantine alchemy
 * episode looks like a bad match until you learn what it was cited for.
 * Generated by scripts/enrichment/shwep-work-facts.mjs --notes (${MODEL}).
 */
export const SHWEP_WORK_NOTES: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
  fs.writeFileSync(path.join(ROOT, 'src/data/shwep-work-notes.ts'), file);
  console.log(`wrote ${Object.keys(out).length} notes across ${done} episodes`);
}

if (has('--languages')) await runLanguages();
else if (has('--notes')) await runNotes();
else { console.error('pass --languages or --notes'); process.exit(1); }
